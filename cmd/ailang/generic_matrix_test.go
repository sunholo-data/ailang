// A generic body is compiled once, at its defaulted type (`Num a` := int), and
// every consumer of a recorded node type must still give the run-time value's
// answer (#2273 review): the class methods are corrected from the run-time
// values, ShowNormalizer leaves show dynamic on defaulted nodes, and mod_Int
// is corrected like the Num methods. Each module in testdata/generic_matrix/mx
// computes one operator shape and prints `<form><T>=…` lines, T the argument
// type (I int, F float, S string). `twin<T>` is the monomorphic function, the
// reference; every other form must print what it prints, on the evaluator and
// the strict VM. The forms (the follow-up review's mx2 matrix, generated by its
// genmx2.py; the older modules have only `gen`):
//
//	genR  a rigid signature `genR[a](x: a, y: a)`
//	genU  an unannotated function `genU(x, y)`
//	genL  a let-bound lambda inside a rigid function
//	genF  an annotated function literal inside a rigid function
//	twinL a let-bound lambda inside the MONOMORPHIC function
//
// The inner-lambda forms are the ones whose node types are recorded before the
// declaration's substitution is applied (markDefaulted); a consumer, or a
// recording, that misses them fails here (mutant MD2 of that review). A new
// consumer that picks an implementation from a defaulted type fails here.
func TestGenericBodiesMatchTheirMonomorphicTwins(t *testing.T) {
	bin := buildAilang(t)
	dir, err := filepath.Abs(filepath.Join("testdata", "generic_matrix"))
	if err != nil {
		t.Fatal(err)
	}
	files, err := filepath.Glob(filepath.Join(dir, "mx", "*.ail"))
	if err != nil || len(files) < 30 {
		t.Fatalf("matrix modules missing (%d found): %v", len(files), err)
	}
	pair := regexp.MustCompile(`^\s*(gen[RULF]?|twinL?)([IFS])=(.*)$`)
	for _, file := range files {
		name := strings.TrimSuffix(filepath.Base(file), ".ail")
		t.Run(name, func(t *testing.T) {
			for _, engine := range [][]string{nil, {"--strict-bytecode"}} {
				args := append([]string{"run", "--quiet"}, engine...)
				args = append(args, "--caps", "IO", "--entry", "main", "mx/"+name+".ail")
				out, stderr, code := runAilangIn(t, bin, dir, args...)
				if code != 0 {
					t.Fatalf("%s %v: exit %d: %s", name, engine, code, stderr)
				}
				twin := map[string]string{}
				var forms [][3]string // form, type, value
				for _, line := range strings.Split(out, "\n") {
					m := pair.FindStringSubmatch(line)
					if m == nil {
						continue
					}
					if m[1] == "twin" {
						twin[m[2]] = m[3]
					} else {
						forms = append(forms, [3]string{m[1], m[2], m[3]})
					}
				}
				if len(forms) == 0 {
					t.Fatalf("%s %v: no gen/twin lines in %q", name, engine, out)
				}
				for _, f := range forms {
					if tw, ok := twin[f[1]]; !ok || tw != f[2] {
						t.Errorf("%s %v: %s%s=%q but twin%s=%q", name, engine, f[0], f[1], f[2], f[1], tw)
					}
				}
			}
		})
	}
}

// mod_Int corrects itself from its run-time values (two floats are float
// modulo) on every call, not only at the generic bodies' defaulted nodes:
// restricting it would need a `%` that stays dynamic after OpLowering, and the
// evaluator's run path requires every intrinsic lowered, while a separate
// dynamic builtin changes the frozen $builtin interface (iface.builtin_freeze)
// and the positional bytecode builtin table (follow-up review of #2273, item 4).
// What must stay loud is an int and a float meeting at `%`: this pins it on both
// engines, so a change that makes it compute silently is noticed.
func TestModIntWithAnIntAndAFloatFailsLoudly(t *testing.T) {
	bin := buildAilang(t)
	dir, err := filepath.Abs(filepath.Join("testdata", "generic_matrix"))
	if err != nil {
		t.Fatal(err)
	}
	for _, c := range []struct {
		engine []string
		want   string
	}{
		{nil, "expected IntValue for arg 0, got *eval.FloatValue"},
		{[]string{"--strict-bytecode"}, "_mod_Int: expected ints"},
	} {
		args := append([]string{"run", "--quiet"}, c.engine...)
		args = append(args, "--caps", "IO", "--entry", "main", "pins/mod_int_float.ail")
		out, stderr, code := runAilangIn(t, bin, dir, args...)
		if code == 0 || !strings.Contains(stderr, c.want) {
			t.Errorf("%v: want a failure naming %q, got exit %d, stdout %q, stderr %q", c.engine, c.want, code, out, stderr)
		}
	}
}

// runAilangIn runs the binary with cwd dir (the matrix modules are `mx/<name>`).
func runAilangIn(t *testing.T, bin, dir string, args ...string) (string, string, int) {
	t.Helper()
	repo, err := filepath.Abs(filepath.Join("..", ".."))
	if err != nil {
		t.Fatal(err)
	}
	t.Setenv("AILANG_STDLIB_PATH", filepath.Join(repo, "std"))
	if _, err := os.Stat(dir); err != nil {
		t.Fatal(err)
	}
	return testutil.RunBounded(t, dir, 60*time.Second, bin, args...)
}
