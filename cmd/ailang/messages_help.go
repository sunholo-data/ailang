package main

import "fmt"

// Help text for messages command

func printMessagesHelp() {
	fmt.Println("Usage: ailang messages <subcommand> [options]")
	fmt.Println()
	fmt.Println("Unified messaging system for agent-to-agent and human-agent communication.")
	fmt.Println("Messages are accessible from both CLI and Collaboration Hub dashboard.")
	fmt.Println()
	fmt.Println("Subcommands:")
	fmt.Printf("  %s                     List messages (default)\n", cyan("list"))
	fmt.Printf("  %s <query>           Semantic search for messages\n", cyan("search"))
	fmt.Printf("  %s                   Find and mark duplicate messages\n", cyan("dedupe"))
	fmt.Printf("  %s                   Cluster unread messages by envelope similarity\n", cyan("triage"))
	fmt.Printf("  %s <id>                Mark message as read\n", cyan("ack"))
	fmt.Printf("  %s <id>              Mark message as unread\n", cyan("unack"))
	fmt.Printf("  %s <inbox> <msg>      Send a message\n", cyan("send"))
	fmt.Printf("  %s <id> <text>       Reply to GitHub issue thread\n", cyan("reply"))
	fmt.Printf("  %s <id>               Show full message content\n", cyan("read"))
	fmt.Printf("  %s <id> --to <inbox> Forward message to another inbox\n", cyan("forward"))
	fmt.Printf("  %s                    Watch for new messages\n", cyan("watch"))
	fmt.Printf("  %s                  Clean up old messages\n", cyan("cleanup"))
	fmt.Printf("  %s            Import GitHub issues as messages\n", cyan("import-github"))
	fmt.Println()
	fmt.Println("List Flags:")
	fmt.Println("  --inbox <name>       Filter by inbox (user, claude-code, etc.)")
	fmt.Println("  --unread             Show only unread messages")
	fmt.Println("  --from <agent>       Filter by sender")
	fmt.Println("  --limit <n>          Maximum messages to show (default: 20)")
	fmt.Println("  --similar-to <id>    Find messages similar to this message ID")
	fmt.Println("  --collapsed          Hide duplicate messages (dup_of is set)")
	fmt.Println("  --duplicates-of <id> Show only duplicates of this message")
	fmt.Println("  --threshold <n>      Similarity threshold for --similar-to (default: 0.70)")
	fmt.Println("  --json               Output as JSON")
	fmt.Println()
	fmt.Println("Search Flags:")
	fmt.Println("  --inbox <name>       Filter by inbox")
	fmt.Println("  --threshold <n>      Minimum similarity (0.0-1.0, default: 0.70)")
	fmt.Println("  --limit <n>          Maximum results (default: 20)")
	fmt.Println("  --max-scan <n>       Maximum messages to scan (default: 1000)")
	fmt.Println("  --neural             Use neural embeddings via Ollama (requires Ollama)")
	fmt.Println("  --simhash            Force SimHash mode (default, fast)")
	fmt.Println("  --space <slot>       Search a specific envelope space (intent, code, context, skill, resolution)")
	fmt.Println("  --json               Output as JSON")
	fmt.Println()
	fmt.Println("Dedupe Flags:")
	fmt.Println("  --inbox <name>       Filter by inbox")
	fmt.Println("  --threshold <n>      Minimum similarity for duplicates (default: 0.95)")
	fmt.Println("  --apply              Actually mark duplicates (default: report only)")
	fmt.Println("  --json               Output as JSON")
	fmt.Println()
	fmt.Println("Ack Flags:")
	fmt.Println("  --all                Acknowledge all unread messages")
	fmt.Println("  --inbox <name>       Filter by inbox when using --all")
	fmt.Println()
	fmt.Println("Forward Flags:")
	fmt.Println("  --to <inbox>         Target inbox (required)")
	fmt.Println("  --reason <text>      Reason for forwarding (logged)")
	fmt.Println()
	fmt.Println("Triage Flags:")
	fmt.Println("  --inbox <name>       Filter by inbox")
	fmt.Println("  --cluster-by <slot>  Envelope slot to cluster on (default: intent)")
	fmt.Println("  --top <n>            Show top-N clusters (default: 10)")
	fmt.Println("  --threshold <n>      Minimum similarity for clustering (default: 0.75)")
	fmt.Println("  --json               Output as JSON")
	fmt.Println()
	fmt.Println("Send Flags:")
	fmt.Println("  --payload <data>     Send payload via flag (alternative to positional arg)")
	fmt.Println("  --title <text>       Message title")
	fmt.Println("  --from <agent>       Sender name (default: cli)")
	fmt.Println("  --correlation <id>   Correlation ID for grouping")
	fmt.Println("  --envelope-code <f>  File paths for code envelope slot (comma-separated)")
	fmt.Println("  --envelope-context <d> Context description for context envelope slot")
	fmt.Println()
	fmt.Println("GitHub Sync Flags (send):")
	fmt.Println("  --github             Also create a GitHub issue")
	fmt.Println("  --type <type>        Message category (any string; bug/feature imply --github)")
	fmt.Println("  --repo <owner/repo>  GitHub repo (overrides config default)")
	fmt.Println()
	fmt.Println("Reply Flags:")
	fmt.Println("  --from <agent>       Sender name for attribution (default: cli)")
	fmt.Println("  --repo <owner/repo>  Override repo from original message")
	fmt.Println()
	fmt.Println("Import GitHub Flags:")
	fmt.Println("  --repo <owner/repo>  GitHub repo to import from")
	fmt.Println("  --labels <list>      Comma-separated labels to filter issues")
	fmt.Println("  --inbox <name>       Target inbox for imported messages (default: user)")
	fmt.Println("  --dry-run            Show what would be imported without importing")
	fmt.Println()
	fmt.Println("Note: Flags can appear before or after positional arguments.")
	fmt.Println()
	fmt.Println("Semantic Envelope (v0.8.1+):")
	fmt.Println("  Messages can carry multi-aspect embedding vectors (semantic envelope).")
	fmt.Println("  Each message has 5 named slots, searchable independently:")
	fmt.Println()
	fmt.Println("    intent      Auto-computed from title + payload. What is being asked?")
	fmt.Println("    code        From --envelope-code files. What code is affected?")
	fmt.Println("    context     From --envelope-context. What was the sender working on?")
	fmt.Println("    skill       From builder API. What expertise is needed?")
	fmt.Println("    resolution  Auto-filled on task completion. How was this resolved?")
	fmt.Println()
	fmt.Println("  Use --space with search to query a specific slot.")
	fmt.Println("  Use triage to cluster messages by slot similarity.")
	fmt.Println("  Requires embeddings provider configured in ~/.ailang/config.yaml")
	fmt.Println("  (ollama, openai, or gemini).")
	fmt.Println()
	fmt.Println("Aliases: msg, messages")
	fmt.Println()
	fmt.Println("Examples:")
	fmt.Printf("  %s                         # Interactive menu (TTY)\n", cyan("ailang messages"))
	fmt.Printf("  %s                         # List all messages\n", cyan("ailang messages list"))
	fmt.Printf("  %s               # List unread only\n", cyan("ailang messages list --unread"))
	fmt.Printf("  %s          # Filter by inbox\n", cyan("ailang messages list --inbox user"))
	fmt.Printf("  %s                   # Read with short ID prefix\n", cyan("ailang messages read 877"))
	fmt.Printf("  %s              # Mark as read\n", cyan("ailang messages ack MSG_ID"))
	fmt.Printf("  %s                     # Ack all unread\n", cyan("ailang messages ack --all"))
	fmt.Printf("  %s   # Send message\n", cyan("ailang messages send user \"Hello\""))
	fmt.Printf("  %s    # Watch for new\n", cyan("ailang messages watch --inbox user"))
	fmt.Println()
	fmt.Println("Forward Examples:")
	fmt.Printf("  %s\n", cyan("ailang messages forward --to design-doc-creator 877"))
	fmt.Printf("  %s\n", cyan("ailang messages forward --to coordinator --reason \"Label changed\" MSG_ID"))
	fmt.Println()
	fmt.Println("GitHub Sync Examples:")
	fmt.Printf("  %s\n", cyan("ailang messages send ailang-core \"Parser crash\" --type bug --github"))
	fmt.Printf("  %s\n", cyan("ailang messages send user \"Add dark mode\" --type feature"))
	fmt.Printf("  %s\n", cyan("ailang messages send user \"Hello\" --github --repo owner/repo"))
	fmt.Printf("  %s\n", cyan("ailang messages reply MSG_ID \"Fixed in v0.5.10\" --from claude-code"))
	fmt.Println()
	fmt.Println("Import GitHub Examples:")
	fmt.Printf("  %s\n", cyan("ailang messages import-github"))
	fmt.Printf("  %s\n", cyan("ailang messages import-github --labels bug,feature"))
	fmt.Printf("  %s\n", cyan("ailang messages import-github --dry-run"))
	fmt.Println()
	fmt.Println("Semantic Search Examples:")
	fmt.Printf("  %s\n", cyan("ailang messages search \"parser error handling\""))
	fmt.Printf("  %s\n", cyan("ailang messages search \"parser\" --threshold 0.5 --limit 10"))
	fmt.Printf("  %s\n", cyan("ailang messages search \"type inference bugs\" --neural"))
	fmt.Printf("  %s\n", cyan("ailang messages list --similar-to MSG_ID"))
	fmt.Printf("  %s\n", cyan("ailang messages list --collapsed"))
	fmt.Println()
	fmt.Println("Neural Search (requires Ollama running locally):")
	fmt.Printf("  %s                  # Start Ollama\n", cyan("ollama serve"))
	fmt.Printf("  %s       # Pull embedding model\n", cyan("ollama pull nomic-embed-text"))
	fmt.Printf("  %s  # Neural search\n", cyan("ailang messages search \"bugs\" --neural"))
	fmt.Println()
	fmt.Println("Envelope Search Examples:")
	fmt.Printf("  %s\n", cyan("ailang messages search --space code \"internal/types\""))
	fmt.Printf("  %s\n", cyan("ailang messages search --space intent \"fix crash\""))
	fmt.Printf("  %s\n", cyan("ailang messages search --space resolution \"parser\""))
	fmt.Println()
	fmt.Println("Send with Envelope:")
	fmt.Printf("  %s\n", cyan("ailang messages send executor \"Fix bug\" --envelope-code internal/types/unify.go"))
	fmt.Printf("  %s\n", cyan("ailang messages send executor \"Fix bug\" --envelope-context \"reviewing ast switches\""))
	fmt.Println()
	fmt.Println("Triage Examples:")
	fmt.Printf("  %s              # Cluster by intent (default)\n", cyan("ailang messages triage"))
	fmt.Printf("  %s  # Cluster by code region\n", cyan("ailang messages triage --cluster-by code"))
	fmt.Printf("  %s           # Top 5 clusters only\n", cyan("ailang messages triage --top 5"))
	fmt.Println()
	fmt.Println("Deduplication Examples:")
	fmt.Printf("  %s                 # Report only\n", cyan("ailang messages dedupe"))
	fmt.Printf("  %s  # Custom threshold\n", cyan("ailang messages dedupe --threshold 0.90"))
	fmt.Printf("  %s       # Apply changes\n", cyan("ailang messages dedupe --apply"))
}
