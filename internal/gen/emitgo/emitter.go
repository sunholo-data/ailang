// Package emitgo emits Go source code from Statement IR.
//
// This is the ONLY package that knows about Go syntax. It reads stmt.Program
// and produces Go source code. It does not import internal/core or internal/ast.
//
// The emitter is intentionally simple — ~400 LOC vs the old codegen's ~10K LOC.
// All complexity lives in the lowering passes (internal/gen/lower/).
package emitgo

import (
	"bytes"
	"fmt"
	"go/format"

	"github.com/sunholo-data/ailang/internal/gen/stmt"
)

// Emit produces Go source code from a Statement IR Program.
func Emit(prog *stmt.Program) ([]byte, error) {
	var buf bytes.Buffer
	e := &emitter{buf: &buf}

	e.writef("// Code generated by ailang. DO NOT EDIT.\n")
	e.writef("package %s\n\n", prog.Package)

	// Imports.
	if len(prog.Imports) > 0 {
		e.writef("import (\n")
		for _, imp := range prog.Imports {
			if imp.Alias != "" {
				e.writef("\t%s %q\n", imp.Alias, imp.Path)
			} else {
				e.writef("\t%q\n", imp.Path)
			}
		}
		e.writef(")\n\n")
	}

	// Type declarations.
	for _, td := range prog.TypeDecls {
		e.emitTypeDecl(td)
		e.writef("\n")
	}

	// Function declarations.
	for _, fd := range prog.FuncDecls {
		e.emitFuncDecl(fd)
		e.writef("\n")
	}

	// Format the Go source.
	src := buf.Bytes()
	formatted, err := format.Source(src)
	if err != nil {
		// Return unformatted source with the error so the caller can debug.
		return src, fmt.Errorf("gofmt failed: %w", err)
	}
	return formatted, nil
}

// EmitTypes produces just the type declarations as a separate file.
func EmitTypes(prog *stmt.Program) ([]byte, error) {
	var buf bytes.Buffer
	e := &emitter{buf: &buf}

	e.writef("// Code generated by ailang. DO NOT EDIT.\n")
	e.writef("package %s\n\n", prog.Package)

	for _, td := range prog.TypeDecls {
		e.emitTypeDecl(td)
		e.writef("\n")
	}

	src := buf.Bytes()
	formatted, err := format.Source(src)
	if err != nil {
		return src, fmt.Errorf("gofmt failed: %w", err)
	}
	return formatted, nil
}

// EmitFuncs produces just the function declarations as a separate file.
func EmitFuncs(prog *stmt.Program, moduleName string) ([]byte, error) {
	var buf bytes.Buffer
	e := &emitter{buf: &buf}

	e.writef("// Code generated by ailang. DO NOT EDIT.\n")
	e.writef("package %s\n\n", prog.Package)

	// Emit imports needed by this module's functions.
	if len(prog.Imports) > 0 {
		e.writef("import (\n")
		for _, imp := range prog.Imports {
			if imp.Alias != "" {
				e.writef("\t%s %q\n", imp.Alias, imp.Path)
			} else {
				e.writef("\t%q\n", imp.Path)
			}
		}
		e.writef(")\n\n")
	}

	for _, fd := range prog.FuncDecls {
		if moduleName != "" && fd.Module != "" && fd.Module != moduleName {
			continue
		}
		e.emitFuncDecl(fd)
		e.writef("\n")
	}

	src := buf.Bytes()
	formatted, err := format.Source(src)
	if err != nil {
		return src, fmt.Errorf("gofmt failed: %w", err)
	}
	return formatted, nil
}

type emitter struct {
	buf    *bytes.Buffer
	indent int
}

func (e *emitter) writef(format string, args ...interface{}) {
	fmt.Fprintf(e.buf, format, args...)
}

func (e *emitter) writeIndent() {
	for i := 0; i < e.indent; i++ {
		e.buf.WriteString("\t")
	}
}

func (e *emitter) writeLine(format string, args ...interface{}) {
	e.writeIndent()
	fmt.Fprintf(e.buf, format, args...)
	e.buf.WriteString("\n")
}
