// Package golang provides Go code generation from AILANG Core AST.
// This file generates type class dictionary implementations.
package golang

import (
	"bytes"
	"go/format"
)

// DerivedEqType stores information about an ADT type that derives Eq.
// M-CODEGEN-DICTIONARIES M4: Used to generate dict_Eq_<TypeName> for ADTs.
type DerivedEqType struct {
	TypeName     string   // Go type name (e.g., "Color")
	Constructors []string // List of constructor names (e.g., ["Red", "Green", "Blue"])
}

// derivedEqTypes tracks ADT types that need Eq dictionary generation.
// M-CODEGEN-DICTIONARIES M4: Populated by RegisterDerivedEqType.
var derivedEqTypes []DerivedEqType

// RegisterDerivedEqType registers an ADT type for derived Eq dictionary generation.
// M-CODEGEN-DICTIONARIES M4: Called during compilation for types with `deriving (Eq)`.
func (g *Generator) RegisterDerivedEqType(typeName string, constructors []string) {
	derivedEqTypes = append(derivedEqTypes, DerivedEqType{
		TypeName:     typeName,
		Constructors: constructors,
	})
}

// ClearDerivedEqTypes clears the derived Eq types registry.
// M-CODEGEN-DICTIONARIES M4: Called at start of compilation for fresh state.
func ClearDerivedEqTypes() {
	derivedEqTypes = nil
}

// GenerateDictionaries produces the dictionaries.go file containing
// type class dictionary implementations for built-in types.
// M-CODEGEN-DICTIONARIES: Generates dict_Num_Int, dict_Ord_*, dict_Eq_*, etc.
func (g *Generator) GenerateDictionaries() ([]byte, error) {
	var buf bytes.Buffer

	buf.WriteString("// Code generated by ailang. DO NOT EDIT.\n")
	buf.WriteString("// Type class dictionary implementations.\n")
	buf.WriteString("package " + g.PackageName + "\n\n")

	// M-CODEGEN-DICTIONARIES M4: Import reflect for derived Eq comparison if needed
	if len(derivedEqTypes) > 0 {
		buf.WriteString("import \"reflect\"\n\n")
	}

	// Generate Num dictionaries (arithmetic operations)
	generateNumDictionary(&buf, "Int", "int64")
	generateNumDictionary(&buf, "Float", "float64")

	// Generate Ord dictionaries (comparison operations)
	generateOrdDictionary(&buf, "Int", "int64")
	generateOrdDictionary(&buf, "Float", "float64")
	generateOrdDictionary(&buf, "String", "string")

	// Generate Eq dictionaries (equality operations)
	generateEqDictionary(&buf, "Int", "int64")
	generateEqDictionary(&buf, "Float", "float64")
	generateEqDictionary(&buf, "String", "string")
	generateEqDictionary(&buf, "Bool", "bool")

	// M-CODEGEN-DICTIONARIES M4: Generate derived Eq dictionaries for ADT types
	for _, adt := range derivedEqTypes {
		generateDerivedEqDictionary(&buf, adt.TypeName)
	}

	// Format the generated code
	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		// Return unformatted code with error for debugging
		return buf.Bytes(), err
	}
	return formatted, nil
}

// generateNumDictionary generates a Num type class dictionary for arithmetic.
// Methods: Add, Sub, Mul, Div, Neg, Abs
func generateNumDictionary(buf *bytes.Buffer, typeName, goType string) {
	buf.WriteString("// dict_Num_" + typeName + " provides Num type class methods for " + goType + "\n")
	buf.WriteString("var dict_Num_" + typeName + " = struct {\n")
	buf.WriteString("\tAdd func(interface{}, interface{}) interface{}\n")
	buf.WriteString("\tSub func(interface{}, interface{}) interface{}\n")
	buf.WriteString("\tMul func(interface{}, interface{}) interface{}\n")
	buf.WriteString("\tDiv func(interface{}, interface{}) interface{}\n")
	buf.WriteString("\tNeg func(interface{}) interface{}\n")
	buf.WriteString("\tAbs func(interface{}) interface{}\n")
	buf.WriteString("}{\n")

	// Add
	buf.WriteString("\tAdd: func(x, y interface{}) interface{} { return x.(" + goType + ") + y.(" + goType + ") },\n")
	// Sub
	buf.WriteString("\tSub: func(x, y interface{}) interface{} { return x.(" + goType + ") - y.(" + goType + ") },\n")
	// Mul
	buf.WriteString("\tMul: func(x, y interface{}) interface{} { return x.(" + goType + ") * y.(" + goType + ") },\n")
	// Div
	buf.WriteString("\tDiv: func(x, y interface{}) interface{} { return x.(" + goType + ") / y.(" + goType + ") },\n")
	// Neg
	buf.WriteString("\tNeg: func(x interface{}) interface{} { return -x.(" + goType + ") },\n")
	// Abs
	if goType == "int64" {
		buf.WriteString("\tAbs: func(x interface{}) interface{} {\n")
		buf.WriteString("\t\tv := x.(int64)\n")
		buf.WriteString("\t\tif v < 0 { return -v }\n")
		buf.WriteString("\t\treturn v\n")
		buf.WriteString("\t},\n")
	} else {
		// float64 - use math.Abs but inline since we don't import math
		buf.WriteString("\tAbs: func(x interface{}) interface{} {\n")
		buf.WriteString("\t\tv := x.(float64)\n")
		buf.WriteString("\t\tif v < 0 { return -v }\n")
		buf.WriteString("\t\treturn v\n")
		buf.WriteString("\t},\n")
	}

	buf.WriteString("}\n\n")
}

// generateOrdDictionary generates an Ord type class dictionary for comparisons.
// Methods: Lt, Gt, Lte, Gte
func generateOrdDictionary(buf *bytes.Buffer, typeName, goType string) {
	buf.WriteString("// dict_Ord_" + typeName + " provides Ord type class methods for " + goType + "\n")
	buf.WriteString("var dict_Ord_" + typeName + " = struct {\n")
	buf.WriteString("\tLt  func(interface{}, interface{}) interface{}\n")
	buf.WriteString("\tGt  func(interface{}, interface{}) interface{}\n")
	buf.WriteString("\tLte func(interface{}, interface{}) interface{}\n")
	buf.WriteString("\tGte func(interface{}, interface{}) interface{}\n")
	buf.WriteString("}{\n")

	buf.WriteString("\tLt:  func(x, y interface{}) interface{} { return x.(" + goType + ") < y.(" + goType + ") },\n")
	buf.WriteString("\tGt:  func(x, y interface{}) interface{} { return x.(" + goType + ") > y.(" + goType + ") },\n")
	buf.WriteString("\tLte: func(x, y interface{}) interface{} { return x.(" + goType + ") <= y.(" + goType + ") },\n")
	buf.WriteString("\tGte: func(x, y interface{}) interface{} { return x.(" + goType + ") >= y.(" + goType + ") },\n")

	buf.WriteString("}\n\n")
}

// generateEqDictionary generates an Eq type class dictionary for equality.
// Methods: Eq, Neq
func generateEqDictionary(buf *bytes.Buffer, typeName, goType string) {
	buf.WriteString("// dict_Eq_" + typeName + " provides Eq type class methods for " + goType + "\n")
	buf.WriteString("var dict_Eq_" + typeName + " = struct {\n")
	buf.WriteString("\tEq  func(interface{}, interface{}) interface{}\n")
	buf.WriteString("\tNeq func(interface{}, interface{}) interface{}\n")
	buf.WriteString("}{\n")

	buf.WriteString("\tEq:  func(x, y interface{}) interface{} { return x.(" + goType + ") == y.(" + goType + ") },\n")
	buf.WriteString("\tNeq: func(x, y interface{}) interface{} { return x.(" + goType + ") != y.(" + goType + ") },\n")

	buf.WriteString("}\n\n")
}

// generateDerivedEqDictionary generates an Eq dictionary for an ADT type with deriving (Eq).
// M-CODEGEN-DICTIONARIES M4: Uses structural comparison (Kind + Fields via reflect.DeepEqual).
func generateDerivedEqDictionary(buf *bytes.Buffer, typeName string) {
	goType := "*" + typeName
	buf.WriteString("// dict_Eq_" + typeName + " provides Eq type class methods for " + typeName + " (derived)\n")
	buf.WriteString("var dict_Eq_" + typeName + " = struct {\n")
	buf.WriteString("\tEq  func(interface{}, interface{}) interface{}\n")
	buf.WriteString("\tNeq func(interface{}, interface{}) interface{}\n")
	buf.WriteString("}{\n")

	// Eq: Compare Kind and Fields using reflect.DeepEqual
	buf.WriteString("\tEq: func(x, y interface{}) interface{} {\n")
	buf.WriteString("\t\ta, b := x.(" + goType + "), y.(" + goType + ")\n")
	buf.WriteString("\t\tif a == nil && b == nil { return true }\n")
	buf.WriteString("\t\tif a == nil || b == nil { return false }\n")
	buf.WriteString("\t\tif a.Kind != b.Kind { return false }\n")
	buf.WriteString("\t\treturn reflect.DeepEqual(a, b)\n")
	buf.WriteString("\t},\n")

	// Neq: Negate Eq (inline to avoid initialization cycle)
	buf.WriteString("\tNeq: func(x, y interface{}) interface{} {\n")
	buf.WriteString("\t\ta, b := x.(" + goType + "), y.(" + goType + ")\n")
	buf.WriteString("\t\tif a == nil && b == nil { return false }\n")
	buf.WriteString("\t\tif a == nil || b == nil { return true }\n")
	buf.WriteString("\t\tif a.Kind != b.Kind { return true }\n")
	buf.WriteString("\t\treturn !reflect.DeepEqual(a, b)\n")
	buf.WriteString("\t},\n")

	buf.WriteString("}\n\n")
}
