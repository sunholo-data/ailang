package golang

import (
	"bytes"
	"fmt"
	"go/format"
	"strings"

	"github.com/sunholo/ailang/internal/ast"
)

// ADTGenerator generates Go code for AILANG algebraic data types.
// Uses the discriminator struct pattern for sum types (not interfaces).
type ADTGenerator struct {
	PackageName string
	buf         bytes.Buffer
	indent      int
	// adtSliceTypes tracks ADT type names that appear in list fields.
	// M-DX12: Used to generate typed slice converters for world boundary marshalling.
	adtSliceTypes map[string]bool
	// M-CODEGEN-VALUE-TYPES: Track record categories for value vs pointer field types.
	// valueRecords contains names of records that should be passed by value (leaf records).
	valueRecords map[string]bool
	// valueThreshold is the maximum field count for value-type records.
	// Records with <= this many fields AND all primitive fields are value types.
	valueThreshold int
}

// NewADTGenerator creates a new ADT code generator.
func NewADTGenerator(packageName string) *ADTGenerator {
	return &ADTGenerator{
		PackageName:    packageName,
		adtSliceTypes:  make(map[string]bool),
		valueRecords:   make(map[string]bool),
		valueThreshold: 4, // Default: records with ≤4 primitive fields are values
	}
}

// SetValueThreshold sets the maximum field count for value-type records.
// M-CODEGEN-VALUE-TYPES: Records with <= threshold fields AND all primitive fields
// are generated as value types instead of pointers.
func (g *ADTGenerator) SetValueThreshold(threshold int) {
	g.valueThreshold = threshold
}

// GetValueThreshold returns the current value threshold.
func (g *ADTGenerator) GetValueThreshold() int {
	return g.valueThreshold
}

// GetADTSliceTypes returns the set of ADT types that appear in list fields.
// M-DX12: Used by Generator to generate typed slice converters.
func (g *ADTGenerator) GetADTSliceTypes() map[string]bool {
	return g.adtSliceTypes
}

// GenerateTypeDecl generates Go code for a type declaration.
func (g *ADTGenerator) GenerateTypeDecl(decl *ast.TypeDecl) ([]byte, error) {
	g.buf.Reset()
	g.indent = 0

	// Write package header
	g.writef("// Code generated by ailang. DO NOT EDIT.\n")
	g.writef("package %s\n\n", g.PackageName)

	// Generate based on definition type
	switch def := decl.Definition.(type) {
	case *ast.AlgebraicType:
		if err := g.generateSumType(decl.Name, decl.TypeParams, def, decl.Exported); err != nil {
			return nil, err
		}
	case *ast.RecordType:
		if err := g.generateRecordType(decl.Name, decl.TypeParams, def, decl.Exported); err != nil {
			return nil, err
		}
	case *ast.TypeAlias:
		if err := g.generateTypeAlias(decl.Name, decl.TypeParams, def, decl.Exported); err != nil {
			return nil, err
		}
	default:
		return nil, fmt.Errorf("unsupported type definition: %T", decl.Definition)
	}

	// Format the generated code
	formatted, err := format.Source(g.buf.Bytes())
	if err != nil {
		return g.buf.Bytes(), fmt.Errorf("format error: %w", err)
	}
	return formatted, nil
}

// GenerateTypeDecls generates Go code for multiple type declarations.
func (g *ADTGenerator) GenerateTypeDecls(decls []*ast.TypeDecl) ([]byte, error) {
	g.buf.Reset()
	g.indent = 0

	// Write package header
	g.writef("// Code generated by ailang. DO NOT EDIT.\n")
	g.writef("package %s\n\n", g.PackageName)

	// Generate each type
	for _, decl := range decls {
		switch def := decl.Definition.(type) {
		case *ast.AlgebraicType:
			if err := g.generateSumType(decl.Name, decl.TypeParams, def, decl.Exported); err != nil {
				return nil, err
			}
		case *ast.RecordType:
			if err := g.generateRecordType(decl.Name, decl.TypeParams, def, decl.Exported); err != nil {
				return nil, err
			}
		case *ast.TypeAlias:
			if err := g.generateTypeAlias(decl.Name, decl.TypeParams, def, decl.Exported); err != nil {
				return nil, err
			}
		default:
			return nil, fmt.Errorf("unsupported type definition: %T", decl.Definition)
		}
	}

	// Format the generated code
	formatted, err := format.Source(g.buf.Bytes())
	if err != nil {
		return g.buf.Bytes(), fmt.Errorf("format error: %w", err)
	}
	return formatted, nil
}

// generateSumType generates a discriminator-based sum type.
// This is the key pattern for game engine performance.
func (g *ADTGenerator) generateSumType(name string, typeParams []string, adt *ast.AlgebraicType, exported bool) error {
	goTypeName := ToGoTypeName(name)
	kindTypeName := ToKindTypeName(name)

	// Generate kind enum type
	g.writef("// %s discriminates between variants of %s\n", kindTypeName, goTypeName)
	g.writef("type %s int\n\n", kindTypeName)

	// Generate kind constants
	g.writef("const (\n")
	g.indent++
	for i, ctor := range adt.Constructors {
		constName := ToKindConstName(name, ctor.Name)
		if i == 0 {
			g.writef("%s %s = iota\n", constName, kindTypeName)
		} else {
			g.writef("%s\n", constName)
		}
	}
	g.indent--
	g.writef(")\n\n")

	// Generate variant structs
	for _, ctor := range adt.Constructors {
		if err := g.generateVariantStruct(name, ctor); err != nil {
			return err
		}
	}

	// Generate main discriminated union struct
	g.writef("// %s is a sum type (discriminated union)\n", goTypeName)
	g.writef("type %s struct {\n", goTypeName)
	g.indent++
	g.writef("Kind %s\n", kindTypeName)
	for _, ctor := range adt.Constructors {
		variantStructName := ToVariantStructName(name, ctor.Name)
		// Use pointer to allow nil (only populated variant is non-nil)
		g.writef("%s *%s\n", ToPascalCase(ctor.Name), variantStructName)
	}
	g.indent--
	g.writef("}\n\n")

	// Generate constructor functions
	for _, ctor := range adt.Constructors {
		if err := g.generateVariantConstructor(name, ctor); err != nil {
			return err
		}
	}

	// Generate Is<Variant> methods for pattern matching
	for _, ctor := range adt.Constructors {
		g.generateIsVariantMethod(name, ctor)
	}

	return nil
}

// generateVariantStruct generates a struct for a sum type constructor.
func (g *ADTGenerator) generateVariantStruct(typeName string, ctor *ast.Constructor) error {
	structName := ToVariantStructName(typeName, ctor.Name)

	g.writef("// %s holds data for the %s variant\n", structName, ctor.Name)
	g.writef("type %s struct {\n", structName)
	g.indent++

	for i, field := range ctor.Fields {
		goType := g.mapASTType(field.Type)
		// Use named field if available, otherwise use positional (Value0, Value1, ...)
		var fieldName string
		if field.Name != "" {
			fieldName = ToPascalCase(field.Name)
		} else {
			fieldName = fmt.Sprintf("Value%d", i)
		}
		g.writef("%s %s\n", fieldName, goType)
	}

	g.indent--
	g.writef("}\n\n")

	return nil
}

// generateVariantConstructor generates a constructor function for a variant.
func (g *ADTGenerator) generateVariantConstructor(typeName string, ctor *ast.Constructor) error {
	constructorName := "New" + ToVariantStructName(typeName, ctor.Name)
	goTypeName := ToGoTypeName(typeName)
	variantStructName := ToVariantStructName(typeName, ctor.Name)
	kindConst := ToKindConstName(typeName, ctor.Name)

	// Build parameter list
	var params []string
	var assignments []string
	for i, field := range ctor.Fields {
		goType := g.mapASTType(field.Type)
		// Use named field if available, otherwise use positional
		var paramName, fieldName string
		if field.Name != "" {
			paramName = field.Name // Use original name for param
			fieldName = ToPascalCase(field.Name)
		} else {
			paramName = fmt.Sprintf("v%d", i)
			fieldName = fmt.Sprintf("Value%d", i)
		}
		params = append(params, fmt.Sprintf("%s %s", paramName, goType))
		assignments = append(assignments, fmt.Sprintf("%s: %s", fieldName, paramName))
	}

	g.writef("// %s creates a new %s variant\n", constructorName, ctor.Name)
	g.writef("func %s(%s) *%s {\n", constructorName, strings.Join(params, ", "), goTypeName)
	g.indent++
	g.writef("return &%s{\n", goTypeName)
	g.indent++
	g.writef("Kind: %s,\n", kindConst)
	if len(assignments) > 0 {
		g.writef("%s: &%s{%s},\n", ToPascalCase(ctor.Name), variantStructName, strings.Join(assignments, ", "))
	} else {
		g.writef("%s: &%s{},\n", ToPascalCase(ctor.Name), variantStructName)
	}
	g.indent--
	g.writef("}\n")
	g.indent--
	g.writef("}\n\n")

	return nil
}

// generateIsVariantMethod generates an Is<Variant>() method for easy pattern matching.
func (g *ADTGenerator) generateIsVariantMethod(typeName string, ctor *ast.Constructor) {
	goTypeName := ToGoTypeName(typeName)
	methodName := "Is" + ToPascalCase(ctor.Name)
	kindConst := ToKindConstName(typeName, ctor.Name)

	g.writef("// %s returns true if this is a %s variant\n", methodName, ctor.Name)
	g.writef("func (v *%s) %s() bool {\n", goTypeName, methodName)
	g.indent++
	g.writef("return v.Kind == %s\n", kindConst)
	g.indent--
	g.writef("}\n\n")
}

// generateRecordType generates a plain Go struct for a record type.
func (g *ADTGenerator) generateRecordType(name string, typeParams []string, rec *ast.RecordType, exported bool) error {
	goTypeName := ToGoTypeName(name)

	// M-CODEGEN-VALUE-TYPES: Analyze if this record qualifies as a value type
	// before generating field types (so nested records can reference it)
	if g.isLeafRecordAST(rec) && len(rec.Fields) <= g.valueThreshold {
		g.valueRecords[goTypeName] = true
	}

	g.writef("// %s is a record type\n", goTypeName)
	g.writef("type %s struct {\n", goTypeName)
	g.indent++

	for _, field := range rec.Fields {
		goType := g.mapASTType(field.Type)
		g.writef("%s %s\n", ToGoFieldName(field.Name), goType)
	}

	g.indent--
	g.writef("}\n\n")

	return nil
}

// isLeafRecordAST checks if a record type has only primitive fields.
// M-CODEGEN-VALUE-TYPES: Leaf records can be passed by value.
func (g *ADTGenerator) isLeafRecordAST(rec *ast.RecordType) bool {
	for _, field := range rec.Fields {
		if !g.isPrimitiveASTType(field.Type) {
			return false
		}
	}
	return true
}

// isPrimitiveASTType checks if an AST type is a primitive Go type.
func (g *ADTGenerator) isPrimitiveASTType(t ast.Type) bool {
	switch typ := t.(type) {
	case *ast.SimpleType:
		goType := g.mapNamedType(typ.Name)
		// Only primitives that map to Go primitives
		switch goType {
		case "int64", "float64", "bool", "string":
			return true
		default:
			return false
		}
	case *ast.ListType:
		// Slices of primitives are allowed in leaf records
		return g.isPrimitiveASTType(typ.Element)
	default:
		// TypeVar, TupleType, FunctionType, etc. are not primitive
		return false
	}
}

// generateTypeAlias generates a Go type alias.
func (g *ADTGenerator) generateTypeAlias(name string, typeParams []string, alias *ast.TypeAlias, exported bool) error {
	goTypeName := ToGoTypeName(name)
	goTargetType := g.mapASTType(alias.Target)

	g.writef("// %s is a type alias\n", goTypeName)
	g.writef("type %s = %s\n\n", goTypeName, goTargetType)

	return nil
}

// mapASTType converts an AST type to a Go type string.
func (g *ADTGenerator) mapASTType(t ast.Type) string {
	if t == nil {
		return "interface{}"
	}

	switch typ := t.(type) {
	case *ast.SimpleType:
		goType := g.mapNamedType(typ.Name)
		// M-CODEGEN-POINTER-RETURN-TYPES: User-defined types need pointers to match ADT constructor returns
		// All ADT values are pointers, so struct fields holding ADTs must be pointers
		// M-CODEGEN-VALUE-TYPES: EXCEPT value records (leaf records ≤threshold fields) use value types
		if IsUserDefinedType(goType) {
			if g.valueRecords[goType] {
				return goType // Value type - no pointer
			}
			return "*" + goType
		}
		return goType

	case *ast.TypeVar:
		// Type variables become interface{} in Go
		return "interface{}"

	case *ast.ListType:
		elemType := g.mapASTType(typ.Element)
		// M-DX12: For ADT/user-defined element types, generate typed slice []*ADTType
		// World boundary marshalling converts []interface{} to typed slices at profile boundaries
		// M-CODEGEN-VALUE-TYPES: Value records use []Type instead of []*Type
		if IsUserDefinedType(elemType) {
			// Track this ADT type for converter generation (strip * prefix for tracking)
			baseType := strings.TrimPrefix(elemType, "*")
			g.adtSliceTypes[baseType] = true
			// M-CODEGEN-VALUE-TYPES: Value records already have no "*" prefix
			// M-CODEGEN-POINTER-RETURN-TYPES: Pointer types already have "*" prefix
			if g.valueRecords[elemType] || strings.HasPrefix(elemType, "*") {
				return fmt.Sprintf("[]%s", elemType)
			}
			return fmt.Sprintf("[]*%s", elemType)
		}
		return fmt.Sprintf("[]%s", elemType)

	case *ast.ArrayType:
		elemType := g.mapASTType(typ.Element)
		// M-DX12: Same as ListType - generate typed slice for ADT elements
		// M-CODEGEN-VALUE-TYPES: Value records use []Type instead of []*Type
		if IsUserDefinedType(elemType) {
			baseType := strings.TrimPrefix(elemType, "*")
			g.adtSliceTypes[baseType] = true
			if g.valueRecords[elemType] || strings.HasPrefix(elemType, "*") {
				return fmt.Sprintf("[]%s", elemType)
			}
			return fmt.Sprintf("[]*%s", elemType)
		}
		return fmt.Sprintf("[]%s", elemType)

	case *ast.TupleType:
		// Tuples become slices of interface{} for simplicity
		return "[]interface{}"

	case *ast.RecordType:
		// Inline records become map[string]interface{} for simplicity
		return "map[string]interface{}"

	case *ast.FuncType:
		// Functions need more complex handling
		return "interface{}"

	// M-TAPP-FIX: Handle TypeApp (generic type application like Option[int])
	case *ast.TypeApp:
		// M-CODEGEN-LIST-TYPE: Handle list types normalized from [T] syntax
		// Parser creates TypeApp("list", [T]) for [T] syntax (DX-17 Phase 2)
		if typ.Constructor == "list" && len(typ.Args) > 0 {
			elemType := g.mapASTType(typ.Args[0])
			// Same logic as ast.ListType case
			if IsUserDefinedType(elemType) {
				baseType := strings.TrimPrefix(elemType, "*")
				g.adtSliceTypes[baseType] = true
				if g.valueRecords[elemType] || strings.HasPrefix(elemType, "*") {
					return fmt.Sprintf("[]%s", elemType)
				}
				return fmt.Sprintf("[]*%s", elemType)
			}
			return fmt.Sprintf("[]%s", elemType)
		}

		// For other generic types, use the constructor name with pointer for ADTs
		goType := g.mapNamedType(typ.Constructor)
		// Most generic types (Option, Result, etc.) are ADTs and need pointers
		if IsUserDefinedType(goType) {
			return "*" + goType
		}
		return goType

	default:
		return "interface{}"
	}
}

// IsUserDefinedType returns true if the Go type is a user-defined type (ADT, struct, etc.)
// rather than a primitive type. Used to determine if slice elements need interface{} wrapping.
// M-CODEGEN-SUSTAINABILITY: Exported so compile_types.go can use the same implementation.
func IsUserDefinedType(goType string) bool {
	// Primitives that don't need interface{} wrapping
	switch goType {
	case "int64", "float64", "bool", "string", "interface{}", "struct{}",
		"map[string]interface{}", "map[string]any", "[]interface{}":
		return false
	default:
		// M-CODEGEN-MULTIMOD: Slice types like []string, []int64, [][]string are NOT
		// user-defined types. Without this check, [[string]] registers "[]string" as an
		// ADT slice type, producing invalid Go like "ConvertTo[]stringSlice".
		if strings.HasPrefix(goType, "[]") {
			return false
		}
		// Pointers to types (e.g., *Direction) are user-defined
		// Named types (e.g., Direction, NPC) are user-defined
		return true
	}
}

// mapNamedType converts a named type to Go.
func (g *ADTGenerator) mapNamedType(name string) string {
	switch name {
	case "int":
		return "int64"
	case "float":
		return "float64"
	case "bool":
		return "bool"
	case "string":
		return "string"
	case "unit", "()":
		return "struct{}"
	default:
		// User-defined type - use PascalCase
		return ToGoTypeName(name)
	}
}

// Helper methods for output

func (g *ADTGenerator) writef(format string, args ...interface{}) {
	g.buf.WriteString(strings.Repeat("\t", g.indent))
	fmt.Fprintf(&g.buf, format, args...)
}
