// Package golang provides Go code generation from AILANG Core AST.
//
// This file implements contract codegen for M-VERIFY.

package golang

import (
	"bytes"
	"fmt"
	"go/format"

	"github.com/sunholo/ailang/internal/core"
)

// ContractGenerator generates Go code for contract types and context.
// M-VERIFY: Similar to DebugGenerator pattern.
type ContractGenerator struct {
	PackageName string
	buf         bytes.Buffer
	indent      int
}

// NewContractGenerator creates a new Contract code generator.
func NewContractGenerator(packageName string) *ContractGenerator {
	return &ContractGenerator{
		PackageName: packageName,
	}
}

// GenerateContractTypes generates the contract_types.go file content.
// This includes ContractMode, ContractCheck, ContractOutput, and ContractContext.
func (g *ContractGenerator) GenerateContractTypes() ([]byte, error) {
	g.buf.Reset()
	g.indent = 0

	// Write package header
	g.writeln("// Code generated by ailang. DO NOT EDIT.")
	g.writeln("// This file contains Contract verification types and context.")
	g.writeln("")
	g.writef("package %s\n\n", g.PackageName)

	// Generate ContractMode enum
	g.generateContractMode()

	// Generate ContractCheck struct
	g.generateContractCheck()

	// Generate ContractOutput struct
	g.generateContractOutput()

	// Generate ContractContext
	g.generateContractContext()

	// Format the generated code
	formatted, err := format.Source(g.buf.Bytes())
	if err != nil {
		return g.buf.Bytes(), fmt.Errorf("format error: %w", err)
	}
	return formatted, nil
}

func (g *ContractGenerator) generateContractMode() {
	g.writeln("// ContractMode controls how contract violations are handled.")
	g.writeln("type ContractMode int")
	g.writeln("")
	g.writeln("const (")
	g.indent++
	g.writeln("ContractModePanic  ContractMode = iota // Panic on first violation")
	g.writeln("ContractModeReport                     // Collect all violations")
	g.writeln("ContractModeOff                        // Skip all contract checks")
	g.indent--
	g.writeln(")")
	g.writeln("")
}

func (g *ContractGenerator) generateContractCheck() {
	g.writeln("// ContractCheck represents a single contract check result.")
	g.writeln("type ContractCheck struct {")
	g.indent++
	g.writeln("Kind     string // requires, ensures, or invariant")
	g.writeln("Passed   bool   // Whether the contract held")
	g.writeln("Message  string // Contract predicate description")
	g.writeln("Location string // Source location")
	g.writeln("Function string // Function name")
	g.indent--
	g.writeln("}")
	g.writeln("")
}

func (g *ContractGenerator) generateContractOutput() {
	g.writeln("// ContractOutput contains collected contract check results.")
	g.writeln("type ContractOutput struct {")
	g.indent++
	g.writeln("Checks     []ContractCheck")
	g.writeln("Mode       ContractMode")
	g.writeln("TotalCount int")
	g.writeln("PassCount  int")
	g.writeln("FailCount  int")
	g.indent--
	g.writeln("}")
	g.writeln("")
}

func (g *ContractGenerator) generateContractContext() {
	// Struct definition
	g.writeln("// ContractContext is the host-side contract verification handler.")
	g.writeln("type ContractContext struct {")
	g.indent++
	g.writeln("checks   []ContractCheck")
	g.writeln("Mode     ContractMode")
	g.writeln("function string")
	g.indent--
	g.writeln("}")
	g.writeln("")

	// Constructor
	g.writeln("// NewContractContext creates a new Contract context with Panic mode.")
	g.writeln("func NewContractContext() *ContractContext {")
	g.indent++
	g.writeln("return &ContractContext{Mode: ContractModePanic}")
	g.indent--
	g.writeln("}")
	g.writeln("")

	// SetMode
	g.writeln("// SetMode changes how contract violations are handled.")
	g.writeln("func (c *ContractContext) SetMode(mode ContractMode) {")
	g.indent++
	g.writeln("c.Mode = mode")
	g.indent--
	g.writeln("}")
	g.writeln("")

	// SetFunction
	g.writeln("// SetFunction sets the current function for context in error messages.")
	g.writeln("func (c *ContractContext) SetFunction(name string) {")
	g.indent++
	g.writeln("c.function = name")
	g.indent--
	g.writeln("}")
	g.writeln("")

	// CheckRequires
	g.writeln("// CheckRequires verifies a precondition.")
	g.writeln("func (c *ContractContext) CheckRequires(cond bool, msg, location string) {")
	g.indent++
	g.writeln("c.check(\"requires\", cond, msg, location)")
	g.indent--
	g.writeln("}")
	g.writeln("")

	// CheckEnsures
	g.writeln("// CheckEnsures verifies a postcondition.")
	g.writeln("func (c *ContractContext) CheckEnsures(cond bool, msg, location string) {")
	g.indent++
	g.writeln("c.check(\"ensures\", cond, msg, location)")
	g.indent--
	g.writeln("}")
	g.writeln("")

	// Internal check method
	g.writeln("func (c *ContractContext) check(kind string, cond bool, msg, location string) {")
	g.indent++
	g.writeln("if c.Mode == ContractModeOff {")
	g.indent++
	g.writeln("return")
	g.indent--
	g.writeln("}")
	g.writeln("")
	g.writeln("check := ContractCheck{")
	g.indent++
	g.writeln("Kind:     kind,")
	g.writeln("Passed:   cond,")
	g.writeln("Message:  msg,")
	g.writeln("Location: location,")
	g.writeln("Function: c.function,")
	g.indent--
	g.writeln("}")
	g.writeln("")
	g.writeln("if c.Mode == ContractModeReport {")
	g.indent++
	g.writeln("c.checks = append(c.checks, check)")
	g.writeln("return")
	g.indent--
	g.writeln("}")
	g.writeln("")
	g.writeln("// Panic mode")
	g.writeln("if !cond {")
	g.indent++
	g.writeln("panic(fmt.Sprintf(\"contract violation: %s failed in %s at %s: %s\", kind, c.function, location, msg))")
	g.indent--
	g.writeln("}")
	g.writeln("c.checks = append(c.checks, check)")
	g.indent--
	g.writeln("}")
	g.writeln("")

	// Collect
	g.writeln("// Collect returns all contract check results.")
	g.writeln("func (c *ContractContext) Collect() ContractOutput {")
	g.indent++
	g.writeln("passCount := 0")
	g.writeln("failCount := 0")
	g.writeln("for _, check := range c.checks {")
	g.indent++
	g.writeln("if check.Passed {")
	g.indent++
	g.writeln("passCount++")
	g.indent--
	g.writeln("} else {")
	g.indent++
	g.writeln("failCount++")
	g.indent--
	g.writeln("}")
	g.indent--
	g.writeln("}")
	g.writeln("return ContractOutput{")
	g.indent++
	g.writeln("Checks:     c.checks,")
	g.writeln("Mode:       c.Mode,")
	g.writeln("TotalCount: len(c.checks),")
	g.writeln("PassCount:  passCount,")
	g.writeln("FailCount:  failCount,")
	g.indent--
	g.writeln("}")
	g.indent--
	g.writeln("}")
	g.writeln("")

	// Reset
	g.writeln("// Reset clears the contract context for the next run.")
	g.writeln("func (c *ContractContext) Reset() {")
	g.indent++
	g.writeln("c.checks = c.checks[:0]")
	g.writeln("c.function = \"\"")
	g.indent--
	g.writeln("}")
	g.writeln("")

	// HasViolations
	g.writeln("// HasViolations returns true if any contract checks failed.")
	g.writeln("func (c *ContractContext) HasViolations() bool {")
	g.indent++
	g.writeln("for _, check := range c.checks {")
	g.indent++
	g.writeln("if !check.Passed {")
	g.indent++
	g.writeln("return true")
	g.indent--
	g.writeln("}")
	g.indent--
	g.writeln("}")
	g.writeln("return false")
	g.indent--
	g.writeln("}")
}

// Helper methods for output

func (g *ContractGenerator) writeln(s string) {
	for i := 0; i < g.indent; i++ {
		g.buf.WriteString("\t")
	}
	g.buf.WriteString(s)
	g.buf.WriteString("\n")
}

func (g *ContractGenerator) writef(format string, args ...interface{}) {
	for i := 0; i < g.indent; i++ {
		g.buf.WriteString("\t")
	}
	fmt.Fprintf(&g.buf, format, args...)
}

// GenerateRequiresChecks generates Go code for requires contract checks.
// M-VERIFY: Called at the start of function body generation.
// Returns the Go code to insert at function entry.
func GenerateRequiresChecks(contracts []*core.Contract, funcName string) string {
	var buf bytes.Buffer
	for _, c := range contracts {
		if c.Kind != core.RequiresKind {
			continue
		}
		// Generate panic-style check (simple version)
		// Full version would use ContractContext
		buf.WriteString(fmt.Sprintf("\t// Requires: %s\n", c.Message))
		buf.WriteString("\t// TODO: Generate actual predicate check from Core expression\n")
	}
	return buf.String()
}

// GenerateEnsuresChecks generates Go code for ensures contract checks.
// M-VERIFY: Called before return in function body generation.
// Returns the Go code to insert before return.
func GenerateEnsuresChecks(contracts []*core.Contract, funcName string) string {
	var buf bytes.Buffer
	for _, c := range contracts {
		if c.Kind != core.EnsuresKind {
			continue
		}
		buf.WriteString(fmt.Sprintf("\t// Ensures: %s\n", c.Message))
		buf.WriteString("\t// TODO: Generate actual predicate check from Core expression\n")
	}
	return buf.String()
}

// DefaultContractHandler returns the Contract effect handler definition.
func DefaultContractHandler() EffectHandler {
	return EffectHandler{
		Name: "Contract",
		Methods: []HandlerMethod{
			{
				Name:       "CheckRequires",
				Params:     []Param{{Name: "cond", Type: "bool"}, {Name: "msg", Type: "string"}, {Name: "location", Type: "string"}},
				Returns:    []string{},
				Doc:        "CheckRequires verifies a precondition.",
				ExampleDoc: "c.check(\"requires\", cond, msg, location)",
			},
			{
				Name:       "CheckEnsures",
				Params:     []Param{{Name: "cond", Type: "bool"}, {Name: "msg", Type: "string"}, {Name: "location", Type: "string"}},
				Returns:    []string{},
				Doc:        "CheckEnsures verifies a postcondition.",
				ExampleDoc: "c.check(\"ensures\", cond, msg, location)",
			},
		},
	}
}

// generateContractRequiresChecks generates requires contract documentation and checks.
// M-VERIFY Phase 0.5: Always generates comments. When verifyContracts is true,
// also generates actual Go predicate checks.
func (g *Generator) generateContractRequiresChecks() error {
	if g.prog == nil || g.prog.Meta == nil {
		return nil
	}

	meta, ok := g.prog.Meta[g.currentFuncName]
	if !ok || len(meta.Contracts) == 0 {
		return nil
	}

	for _, c := range meta.Contracts {
		if c.Kind != core.RequiresKind {
			continue
		}

		// Always generate comment documenting the contract
		g.writef("// Requires: %s\n", c.Message)

		// Only generate runtime checks when verification is enabled
		if g.verifyContracts {
			// Generate: if !(predicate).(bool) { panic("contract violation: requires: ...") }
			// M-VERIFY: Runtime helpers like GeInt return interface{} so we need the .(bool)
			// assertion. The comparison itself is generated using runtime helpers (not raw Go
			// operators) because operands are interface{} in _impl functions.
			g.writef("if !(")
			if err := g.generateExpr(c.Expr); err != nil {
				return fmt.Errorf("contract predicate: %w", err)
			}
			g.write(").(bool) {\n")
			g.indent++
			g.writef("panic(\"contract violation: requires: %s at %s\")\n", c.Message, c.Location)
			g.indent--
			g.writef("}\n")
		}
	}

	return nil
}

// generateContractEnsuresChecks generates ensures contract documentation and checks.
// M-VERIFY Phase 0.5: Always generates comments. When verifyContracts is true,
// also generates actual Go predicate checks.
// This is called from generateTypedWrapper after the _impl call.
// The 'result' variable must be in scope containing the return value.
func (g *Generator) generateContractEnsuresChecks(funcName string, resultVar string, retType string) error {
	if g.prog == nil || g.prog.Meta == nil {
		return nil
	}

	meta, ok := g.prog.Meta[funcName]
	if !ok || len(meta.Contracts) == 0 {
		return nil
	}

	hasEnsures := false
	for _, c := range meta.Contracts {
		if c.Kind == core.EnsuresKind {
			hasEnsures = true
			break
		}
	}
	if !hasEnsures {
		return nil
	}

	for _, c := range meta.Contracts {
		if c.Kind != core.EnsuresKind {
			continue
		}

		// Always generate comment documenting the contract
		g.writef("// Ensures: %s\n", c.Message)

		// Only generate runtime checks when verification is enabled
		if g.verifyContracts {
			// Generate: if !(predicate) { panic("contract violation: ensures: ...") }
			// For ensures, we're in the typed wrapper so we can use typed comparisons
			// The 'result' identifier in the predicate refers to the result variable
			g.writef("if !(")
			if err := g.generateEnsuresPredicate(c.Expr, resultVar, retType); err != nil {
				return fmt.Errorf("contract predicate: %w", err)
			}
			g.write(") {\n")
			g.indent++
			g.writef("panic(\"contract violation: ensures: %s at %s\")\n", c.Message, c.Location)
			g.indent--
			g.writef("}\n")
		}
	}

	return nil
}

// generateEnsuresPredicate generates Go code for an ensures predicate expression.
// It substitutes 'result' with the actual result variable and uses typed operations
// since we're in the typed wrapper context.
func (g *Generator) generateEnsuresPredicate(expr core.CoreExpr, resultVar string, retType string) error {
	// Handle different expression types, substituting 'result' identifier
	switch e := expr.(type) {
	case *core.Var:
		// Substitute 'result' with the actual result variable
		if e.Name == "result" {
			g.write(resultVar)
		} else {
			g.write(ToGoVarName(e.Name))
		}
		return nil

	case *core.Lit:
		// Literals are generated directly
		return g.generateLit(e)

	case *core.BinOp:
		// For binary operations, we can use typed Go operators in the wrapper
		// since the result variable is typed
		g.write("(")
		if err := g.generateEnsuresPredicate(e.Left, resultVar, retType); err != nil {
			return err
		}
		g.writef(" %s ", e.Op)
		if err := g.generateEnsuresPredicate(e.Right, resultVar, retType); err != nil {
			return err
		}
		g.write(")")
		return nil

	case *core.UnOp:
		g.writef("(%s", e.Op)
		if err := g.generateEnsuresPredicate(e.Operand, resultVar, retType); err != nil {
			return err
		}
		g.write(")")
		return nil

	case *core.Intrinsic:
		// M-VERIFY: Handle Intrinsic nodes which represent binary/unary operations
		// after elaboration. Map IntrinsicOp to Go operators for typed context.
		opStr := intrinsicOpToString(e.Op)
		if len(e.Args) == 2 {
			// Binary operation
			g.write("(")
			if err := g.generateEnsuresPredicate(e.Args[0], resultVar, retType); err != nil {
				return err
			}
			g.writef(" %s ", opStr)
			if err := g.generateEnsuresPredicate(e.Args[1], resultVar, retType); err != nil {
				return err
			}
			g.write(")")
		} else if len(e.Args) == 1 {
			// Unary operation
			g.writef("(%s", opStr)
			if err := g.generateEnsuresPredicate(e.Args[0], resultVar, retType); err != nil {
				return err
			}
			g.write(")")
		}
		return nil

	case *core.App:
		// Function application - generate normally but handle result in args
		return g.generateEnsuresApp(e, resultVar, retType)

	default:
		// Fallback to normal expression generation
		// This handles complex expressions but won't substitute 'result'
		return g.generateExpr(expr)
	}
}

// intrinsicOpToString converts IntrinsicOp to Go operator string.
func intrinsicOpToString(op core.IntrinsicOp) string {
	switch op {
	case core.OpAdd:
		return "+"
	case core.OpSub:
		return "-"
	case core.OpMul:
		return "*"
	case core.OpDiv:
		return "/"
	case core.OpMod:
		return "%"
	case core.OpEq:
		return "=="
	case core.OpNe:
		return "!="
	case core.OpLt:
		return "<"
	case core.OpLe:
		return "<="
	case core.OpGt:
		return ">"
	case core.OpGe:
		return ">="
	case core.OpAnd:
		return "&&"
	case core.OpOr:
		return "||"
	case core.OpNot:
		return "!"
	case core.OpNeg:
		return "-"
	case core.OpConcat:
		return "+" // String concat in Go
	default:
		return "?" // Unknown operator
	}
}

// generateEnsuresApp generates a function application within an ensures predicate.
// M-CONTRACTS-OPLOWERING: After op lowering, contract predicates like `result >= 0`
// become App{Func: VarGlobal("$builtin", "ge_Int"), Args: [Var("result"), Lit(0)]}.
// We recognize these lowered builtin calls and generate typed Go operators with
// proper 'result' → resultVar substitution.
func (g *Generator) generateEnsuresApp(app *core.App, resultVar string, retType string) error {
	// Check if this is a lowered builtin comparison/arithmetic call
	if vg, ok := app.Func.(*core.VarGlobal); ok && vg.Ref.Module == "$builtin" {
		if goOp := builtinNameToGoOp(vg.Ref.Name); goOp != "" && len(app.Args) == 2 {
			// Binary builtin: generate as typed Go operator with result substitution
			g.write("(")
			if err := g.generateEnsuresPredicate(app.Args[0], resultVar, retType); err != nil {
				return err
			}
			g.writef(" %s ", goOp)
			if err := g.generateEnsuresPredicate(app.Args[1], resultVar, retType); err != nil {
				return err
			}
			g.write(")")
			return nil
		}
	}
	// Fallback: generate as normal expression (no result substitution possible)
	return g.generateExpr(app)
}

// builtinNameToGoOp maps lowered builtin function names back to Go operators.
// Returns empty string if the builtin doesn't map to a simple Go operator.
func builtinNameToGoOp(name string) string {
	switch name {
	// Comparison operators
	case "ge_Int", "ge_Float", "ge_String":
		return ">="
	case "gt_Int", "gt_Float", "gt_String":
		return ">"
	case "le_Int", "le_Float", "le_String":
		return "<="
	case "lt_Int", "lt_Float", "lt_String":
		return "<"
	case "eq_Int", "eq_Float", "eq_String", "eq_Bool":
		return "=="
	case "ne_Int", "ne_Float", "ne_String", "ne_Bool":
		return "!="
	// Arithmetic operators
	case "add_Int", "add_Float":
		return "+"
	case "sub_Int", "sub_Float":
		return "-"
	case "mul_Int", "mul_Float":
		return "*"
	case "div_Int", "div_Float":
		return "/"
	case "mod_Int":
		return "%"
	default:
		return ""
	}
}
