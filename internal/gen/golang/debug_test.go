func TestGenerateDebugTypesRelease(t *testing.T) {
	gen := NewDebugGenerator("game")

	code, err := gen.GenerateDebugTypesRelease()
	if err != nil {
		t.Fatalf("GenerateDebugTypesRelease failed: %v", err)
	}

	output := string(code)

	// Check build tag
	if !strings.Contains(output, "//go:build release") {
		t.Error("Missing release build tag")
	}

	// Check comment
	if !strings.Contains(output, "Release mode") || !strings.Contains(output, "no-ops") {
		t.Error("Missing release mode comment")
	}

	// Check no-op implementations
	if !strings.Contains(output, "func (d *DebugContext) Log(msg, location string) {}") {
		t.Error("Missing no-op Log implementation")
	}
	if !strings.Contains(output, "func (d *DebugContext) Assert(cond bool, msg, location string) {}") {
		t.Error("Missing no-op Assert implementation")
	}
	if !strings.Contains(output, "func (d *DebugContext) SetTimestamp(t int64) {}") {
		t.Error("Missing no-op SetTimestamp implementation")
	}
	if !strings.Contains(output, "func (d *DebugContext) Reset() {}") {
		t.Error("Missing no-op Reset implementation")
	}

	// Check empty struct
	if !strings.Contains(output, "type DebugContext struct{}") {
		t.Error("Missing empty DebugContext struct")
	}
}

