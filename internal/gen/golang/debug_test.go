func TestDefaultDebugHandler(t *testing.T) {
	handler := DefaultDebugHandler()

	if handler.Name != "Debug" {
		t.Errorf("Expected handler name 'Debug', got %q", handler.Name)
	}

	// Check required methods
	methodNames := make(map[string]bool)
	for _, m := range handler.Methods {
		methodNames[m.Name] = true
	}

	required := []string{"Log", "Assert", "SetTimestamp", "Collect", "Reset"}
	for _, name := range required {
		if !methodNames[name] {
			t.Errorf("Missing required method: %s", name)
		}
	}
}

