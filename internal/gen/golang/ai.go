// Package golang provides Go code generation from AILANG Core AST.
//
// This file implements AI effect codegen for M-GAME-E2.

package golang

import (
	"bytes"
	"fmt"
	"go/format"
)

// AIGenerator generates Go code for AI effect types and context.
type AIGenerator struct {
	PackageName string
	buf         bytes.Buffer
	indent      int
}

// NewAIGenerator creates a new AI code generator.
func NewAIGenerator(packageName string) *AIGenerator {
	return &AIGenerator{
		PackageName: packageName,
	}
}

// GenerateAITypes generates the ai_handler.go file content.
// This includes AIHandler interface, StubAIHandler, AIContext, and ErrNoAIHandler.
func (g *AIGenerator) GenerateAITypes() ([]byte, error) {
	g.buf.Reset()
	g.indent = 0

	// Write package header
	g.writeln("// Code generated by ailang. DO NOT EDIT.")
	g.writeln("// This file contains AI effect types and context.")
	g.writeln("")
	g.writef("package %s\n\n", g.PackageName)

	// Import errors package
	g.writeln("import \"errors\"")
	g.writeln("")

	// Generate ErrNoAIHandler
	g.generateErrNoAIHandler()

	// Generate AIHandler interface
	g.generateAIHandler()

	// Generate StubAIHandler
	g.generateStubAIHandler()

	// Generate AIContext
	g.generateAIContext()

	// Format the generated code
	formatted, err := format.Source(g.buf.Bytes())
	if err != nil {
		return g.buf.Bytes(), fmt.Errorf("format error: %w", err)
	}
	return formatted, nil
}

func (g *AIGenerator) generateErrNoAIHandler() {
	g.writeln("// ErrNoAIHandler is returned when AI.call is invoked without a configured handler.")
	g.writeln("// This prevents silent failures - you must explicitly configure a handler.")
	g.writeln(`var ErrNoAIHandler = errors.New("no AI model configured — add --ai <model> flag (e.g. --ai gemini-2-5-flash), or --ai-stub for testing")`)
	g.writeln("")
}

func (g *AIGenerator) generateAIHandler() {
	g.writeln("// AIHandler interface for pluggable AI implementation.")
	g.writeln("// Implement this interface to provide custom AI behavior:")
	g.writeln("//   - OpenAI/Claude API handler for production")
	g.writeln("//   - Local LLM (Ollama) handler")
	g.writeln("//   - Record/replay handler for debugging")
	g.writeln("//   - StubAIHandler for testing")
	g.writeln("type AIHandler interface {")
	g.indent++
	g.writeln("// Call invokes the AI with the given input string.")
	g.writeln("// Input is typically JSON by convention, but not enforced.")
	g.writeln("// Returns the AI response or an error.")
	g.writeln("Call(input string) (string, error)")
	g.indent--
	g.writeln("}")
	g.writeln("")
}

func (g *AIGenerator) generateStubAIHandler() {
	// Struct definition
	g.writeln("// StubAIHandler returns deterministic placeholder responses for testing.")
	g.writeln("// Use this in tests to avoid real AI calls.")
	g.writeln("type StubAIHandler struct {")
	g.indent++
	g.writeln("defaultResponse string            // Fallback for unmatched inputs")
	g.writeln("responses       map[string]string // Exact input match -> response")
	g.indent--
	g.writeln("}")
	g.writeln("")

	// Constructor
	g.writeln("// NewStubAIHandler creates a stub handler with default Wait response.")
	g.writeln("func NewStubAIHandler() *StubAIHandler {")
	g.indent++
	g.writeln("return &StubAIHandler{")
	g.indent++
	g.writeln(`defaultResponse: "{\"kind\":\"Wait\"}",`)
	g.writeln("responses:       make(map[string]string),")
	g.indent--
	g.writeln("}")
	g.indent--
	g.writeln("}")
	g.writeln("")

	// Call method
	g.writeln("// Call returns a canned response based on exact input match.")
	g.writeln("// If no match found, returns the default response.")
	g.writeln("func (h *StubAIHandler) Call(input string) (string, error) {")
	g.indent++
	g.writeln("if resp, ok := h.responses[input]; ok {")
	g.indent++
	g.writeln("return resp, nil")
	g.indent--
	g.writeln("}")
	g.writeln("return h.defaultResponse, nil")
	g.indent--
	g.writeln("}")
	g.writeln("")

	// SetResponse
	g.writeln("// SetResponse sets a canned response for an exact input match.")
	g.writeln("// Use this in tests to control AI behavior for specific inputs.")
	g.writeln("func (h *StubAIHandler) SetResponse(input, response string) {")
	g.indent++
	g.writeln("h.responses[input] = response")
	g.indent--
	g.writeln("}")
	g.writeln("")

	// SetDefaultResponse
	g.writeln("// SetDefaultResponse sets the fallback response for unmatched inputs.")
	g.writeln("func (h *StubAIHandler) SetDefaultResponse(response string) {")
	g.indent++
	g.writeln("h.defaultResponse = response")
	g.indent--
	g.writeln("}")
	g.writeln("")
}

func (g *AIGenerator) generateAIContext() {
	// Struct definition
	g.writeln("// AIContext holds the handler for the current execution.")
	g.writeln("// Threading pattern matches DebugContext and RNGContext.")
	g.writeln("type AIContext struct {")
	g.indent++
	g.writeln("handler AIHandler")
	g.indent--
	g.writeln("}")
	g.writeln("")

	// Constructor
	g.writeln("// NewAIContext creates a context with the given handler.")
	g.writeln("// IMPORTANT: Pass nil only in tests to verify error handling.")
	g.writeln("// Production code should always provide a real handler.")
	g.writeln("func NewAIContext(handler AIHandler) *AIContext {")
	g.indent++
	g.writeln("return &AIContext{handler: handler}")
	g.indent--
	g.writeln("}")
	g.writeln("")

	// Call method with nil check
	g.writeln("// Call invokes the AI handler with the given input.")
	g.writeln("// Returns ErrNoAIHandler if no handler is configured (no silent fallback).")
	g.writeln("func (c *AIContext) Call(input string) (string, error) {")
	g.indent++
	g.writeln("if c.handler == nil {")
	g.indent++
	g.writeln("return \"\", ErrNoAIHandler")
	g.indent--
	g.writeln("}")
	g.writeln("return c.handler.Call(input)")
	g.indent--
	g.writeln("}")
	g.writeln("")

	// Handler getter (HOST-ONLY)
	g.writeln("// Handler returns the underlying handler.")
	g.writeln("// HOST-ONLY: Not callable from AILANG code.")
	g.writeln("func (c *AIContext) Handler() AIHandler {")
	g.indent++
	g.writeln("return c.handler")
	g.indent--
	g.writeln("}")
}

// Helper methods for output

func (g *AIGenerator) writeln(s string) {
	for i := 0; i < g.indent; i++ {
		g.buf.WriteString("\t")
	}
	g.buf.WriteString(s)
	g.buf.WriteString("\n")
}

func (g *AIGenerator) writef(format string, args ...interface{}) {
	for i := 0; i < g.indent; i++ {
		g.buf.WriteString("\t")
	}
	fmt.Fprintf(&g.buf, format, args...)
}

