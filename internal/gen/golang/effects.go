package golang

import (
	"bytes"
	"fmt"
	"go/format"
	"strings"
)

// EffectHandler describes an effect that needs a handler implementation.
type EffectHandler struct {
	Name    string // Effect name (e.g., "Rand", "Clock")
	Methods []HandlerMethod
}

// HandlerMethod describes a method in an effect handler.
type HandlerMethod struct {
	Name       string   // Method name (e.g., "RandInt")
	Params     []Param  // Parameters
	Returns    []string // Return types
	Doc        string   // Documentation comment
	ExampleDoc string   // Example implementation hint
}

// Param describes a method parameter.
type Param struct {
	Name string
	Type string
}

// EffectsGenerator generates Go code for effect handlers.
type EffectsGenerator struct {
	PackageName string
	buf         bytes.Buffer
	indent      int
}

// NewEffectsGenerator creates a new effects code generator.
func NewEffectsGenerator(packageName string) *EffectsGenerator {
	return &EffectsGenerator{
		PackageName: packageName,
	}
}

// GenerateHandlers generates handler interfaces for the given effects.
func (g *EffectsGenerator) GenerateHandlers(handlers []EffectHandler) ([]byte, error) {
	g.buf.Reset()
	g.indent = 0

	// Write package header
	g.writef("// Code generated by ailang. DO NOT EDIT.\n")
	g.writef("// This file contains effect handler interfaces for your game.\n")
	g.writef("// Implement these interfaces to provide platform-specific behavior.\n")
	g.writef("package %s\n\n", g.PackageName)

	// Generate each handler interface
	for _, h := range handlers {
		if err := g.generateHandler(h); err != nil {
			return nil, err
		}
	}

	// Generate the Handlers struct that collects all handlers
	g.generateHandlersStruct(handlers)

	// Generate Init function
	g.generateInitFunc(handlers)

	// Format the generated code
	formatted, err := format.Source(g.buf.Bytes())
	if err != nil {
		return g.buf.Bytes(), fmt.Errorf("format error: %w", err)
	}
	return formatted, nil
}

func (g *EffectsGenerator) generateHandler(h EffectHandler) error {
	interfaceName := h.Name + "Handler"

	g.writef("// %s provides the %s effect implementation.\n", interfaceName, h.Name)
	g.writef("// Implement this interface to control %s behavior in your game.\n", strings.ToLower(h.Name))
	g.writef("type %s interface {\n", interfaceName)
	g.indent++

	for _, m := range h.Methods {
		// Write method documentation
		if m.Doc != "" {
			g.writef("// %s\n", m.Doc)
		}
		if m.ExampleDoc != "" {
			g.writef("// Example: %s\n", m.ExampleDoc)
		}

		// Build parameter string
		var params []string
		for _, p := range m.Params {
			params = append(params, fmt.Sprintf("%s %s", p.Name, p.Type))
		}
		paramStr := strings.Join(params, ", ")

		// Build return string
		var returnStr string
		if len(m.Returns) == 0 {
			returnStr = ""
		} else if len(m.Returns) == 1 {
			returnStr = " " + m.Returns[0]
		} else {
			returnStr = " (" + strings.Join(m.Returns, ", ") + ")"
		}

		g.writef("%s(%s)%s\n", m.Name, paramStr, returnStr)
	}

	g.indent--
	g.writef("}\n\n")

	return nil
}

func (g *EffectsGenerator) generateHandlersStruct(handlers []EffectHandler) {
	g.writef("// Handlers collects all effect handlers for this module.\n")
	g.writef("type Handlers struct {\n")
	g.indent++

	for _, h := range handlers {
		g.writef("%s %sHandler\n", h.Name, h.Name)
	}

	g.indent--
	g.writef("}\n\n")
}

func (g *EffectsGenerator) generateInitFunc(handlers []EffectHandler) {
	g.writef("// Init initializes the module with the provided handlers.\n")
	g.writef("// Call this before using any functions that require effects.\n")
	g.writef("func Init(h Handlers) {\n")
	g.indent++
	g.writef("handlers = h\n")
	g.indent--
	g.writef("}\n\n")

	g.writef("// handlers is the global handler registry.\n")
	g.writef("var handlers Handlers\n\n")

	// Generate require* guard functions for each handler
	g.generateRequireGuards(handlers)
}

// generateRequireGuards generates helper functions that panic with clear error messages
// if effect handlers are nil. This prevents confusing nil pointer panics.
func (g *EffectsGenerator) generateRequireGuards(handlers []EffectHandler) {
	for _, h := range handlers {
		lowerName := strings.ToLower(h.Name)
		g.writef("// require%s returns the %s handler or panics with a helpful message.\n", h.Name, h.Name)
		g.writef("func require%s() %sHandler {\n", h.Name, h.Name)
		g.indent++
		g.writef("if handlers.%s == nil {\n", h.Name)
		g.indent++
		g.writef("panic(\"%s effect handler not initialized. Call Init() with a %sHandler before using %s_* functions.\")\n",
			h.Name, h.Name, lowerName)
		g.indent--
		g.writef("}\n")
		g.writef("return handlers.%s\n", h.Name)
		g.indent--
		g.writef("}\n\n")
	}
}

func (g *EffectsGenerator) writef(format string, args ...interface{}) {
	g.buf.WriteString(strings.Repeat("\t", g.indent))
	fmt.Fprintf(&g.buf, format, args...)
}

