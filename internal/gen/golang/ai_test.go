func TestGenerateAITypes(t *testing.T) {
	gen := NewAIGenerator("mygame")

	code, err := gen.GenerateAITypes()
	if err != nil {
		t.Fatalf("GenerateAITypes failed: %v", err)
	}

	output := string(code)

	// Check package declaration
	if !strings.Contains(output, "package mygame") {
		t.Error("Missing package declaration")
	}

	// Check generated header
	if !strings.Contains(output, "Code generated by ailang") {
		t.Error("Missing generated header")
	}

	// Check errors import
	if !strings.Contains(output, `import "errors"`) {
		t.Error("Missing errors import")
	}
}

