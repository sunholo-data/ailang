func TestDefaultAIHandler(t *testing.T) {
	handler := DefaultAIHandler()

	if handler.Name != "AI" {
		t.Errorf("Expected handler name 'AI', got %q", handler.Name)
	}

	// Check required methods
	if len(handler.Methods) != 1 {
		t.Errorf("Expected 1 method, got %d", len(handler.Methods))
	}

	if handler.Methods[0].Name != "Call" {
		t.Errorf("Expected method 'Call', got %q", handler.Methods[0].Name)
	}

	// Check Call signature
	call := handler.Methods[0]
	if len(call.Params) != 1 {
		t.Errorf("Expected 1 param, got %d", len(call.Params))
	}
	if call.Params[0].Name != "input" || call.Params[0].Type != "string" {
		t.Errorf("Expected input: string param, got %s: %s", call.Params[0].Name, call.Params[0].Type)
	}
	if len(call.Returns) != 2 || call.Returns[0] != "string" || call.Returns[1] != "error" {
		t.Errorf("Expected returns [string, error], got %v", call.Returns)
	}
}

