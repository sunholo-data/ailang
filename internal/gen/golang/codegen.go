// Package golang provides Go code generation from AILANG Core AST.
//
// This package implements Phase 1 (M-GAME-A) of the game support enablement:
// - ADT → Go struct generation with discriminator pattern
// - Pure function → Go function generation
// - Export keyword support
//
// Generated code uses discriminator structs for sum types (not interfaces)
// to ensure cache-friendly, branch-predictable layouts for game engines.
package golang

import (
	"bytes"
	"fmt"
	"go/format"
	"io"
	"strings"

	"github.com/sunholo/ailang/internal/core"
)

// ADTConstructorInfo holds information about an ADT constructor.
type ADTConstructorInfo struct {
	TypeName    string // The ADT type name (e.g., "Selection")
	CtorName    string // The constructor name (e.g., "SelectionNone")
	GoFuncName  string // The Go constructor function name (e.g., "NewSelectionSelectionNone")
	FieldCount  int    // Number of fields (0 for nullary constructors)
}

// Generator produces Go source code from AILANG Core AST.
type Generator struct {
	// PackageName is the Go package name for generated code
	PackageName string

	// TypeMapper handles AILANG → Go type conversions
	TypeMapper *TypeMapper

	// prog is the current program being generated (for accessing DeclMeta)
	prog *core.Program

	// adtConstructors maps constructor names to their info
	adtConstructors map[string]*ADTConstructorInfo

	// output buffer for generated code
	buf bytes.Buffer

	// indentation level
	indent int

	// errors encountered during generation
	errors []error
}

// New creates a new Generator with the specified package name.
func New(packageName string) *Generator {
	return &Generator{
		PackageName:     packageName,
		TypeMapper:      NewTypeMapper(),
		adtConstructors: make(map[string]*ADTConstructorInfo),
	}
}

// RegisterADTConstructor registers an ADT constructor for proper code generation.
// This enables VarGlobal references to ADT constructors to generate the correct
// Go constructor function calls (e.g., NewSelectionSelectionNone() instead of SelectionNone).
func (g *Generator) RegisterADTConstructor(typeName, ctorName string, fieldCount int) {
	goFuncName := "New" + ToVariantStructName(typeName, ctorName)
	g.adtConstructors[ctorName] = &ADTConstructorInfo{
		TypeName:   typeName,
		CtorName:   ctorName,
		GoFuncName: goFuncName,
		FieldCount: fieldCount,
	}
}

// Generate produces Go source code from a Core program.
// Returns the formatted Go source code.
func (g *Generator) Generate(prog *core.Program) ([]byte, error) {
	g.buf.Reset()
	g.errors = nil
	g.indent = 0
	g.prog = prog // Store for DeclMeta access

	// Write package header
	g.writePackageHeader()

	// Generate code from declarations
	// Core programs store declarations as a flat list with metadata
	for _, decl := range prog.Decls {
		if err := g.generateDecl(decl); err != nil {
			g.errors = append(g.errors, err)
		}
	}

	if len(g.errors) > 0 {
		return nil, fmt.Errorf("generation errors: %v", g.errors)
	}

	// Format the generated code
	return g.formatOutput()
}

// GenerateToWriter writes generated Go code to the provided writer.
func (g *Generator) GenerateToWriter(prog *core.Program, w io.Writer) error {
	code, err := g.Generate(prog)
	if err != nil {
		return err
	}
	_, err = w.Write(code)
	return err
}

// writePackageHeader writes the package declaration and runtime helpers.
func (g *Generator) writePackageHeader() {
	g.writef("// Code generated by ailang. DO NOT EDIT.\n")
	g.writef("package %s\n\n", g.PackageName)

	// Write runtime helpers
	g.writeRuntimeHelpers()
}

// writeRuntimeHelpers writes utility functions needed by generated code.
func (g *Generator) writeRuntimeHelpers() {
	g.writef("// RecordUpdate creates a new record with specified fields updated.\n")
	g.writef("// AILANG: { base | field1: val1, field2: val2 }\n")
	g.writef("func RecordUpdate(base interface{}, updates map[string]interface{}) interface{} {\n")
	g.indent++
	g.writef("baseMap, ok := base.(map[string]interface{})\n")
	g.writef("if !ok {\n")
	g.indent++
	g.writef("return updates\n")
	g.indent--
	g.writef("}\n")
	g.writef("result := make(map[string]interface{}, len(baseMap)+len(updates))\n")
	g.writef("for k, v := range baseMap {\n")
	g.indent++
	g.writef("result[k] = v\n")
	g.indent--
	g.writef("}\n")
	g.writef("for k, v := range updates {\n")
	g.indent++
	g.writef("result[k] = v\n")
	g.indent--
	g.writef("}\n")
	g.writef("return result\n")
	g.indent--
	g.writef("}\n\n")
}

// generateDecl generates Go code for a Core declaration.
func (g *Generator) generateDecl(decl core.CoreExpr) error {
	switch d := decl.(type) {
	case *core.Let:
		return g.generateTopLevelLet(d)
	case *core.LetRec:
		return g.generateTopLevelLetRec(d)
	default:
		// Skip other declaration types for now
		return nil
	}
}

// isExported checks if a declaration name is marked for export.
func (g *Generator) isExported(name string) bool {
	if g.prog == nil || g.prog.Meta == nil {
		return false
	}
	if meta, ok := g.prog.Meta[name]; ok {
		return meta.IsExport
	}
	return false
}

// generateTopLevelLet generates a top-level let binding as a Go var or func.
func (g *Generator) generateTopLevelLet(let *core.Let) error {
	exported := g.isExported(let.Name)

	// Check if it's a function (Lambda body)
	if lam, ok := let.Value.(*core.Lambda); ok {
		return g.generateFuncFromLambda(let.Name, lam, exported)
	}

	// Otherwise generate as a variable
	varName := ToGoFuncName(let.Name, exported) // Use same naming for consistency
	g.writef("var %s = ", varName)
	if err := g.generateExpr(let.Value); err != nil {
		return err
	}
	g.writef("\n\n")
	return nil
}

// generateTopLevelLetRec generates recursive function bindings.
func (g *Generator) generateTopLevelLetRec(letrec *core.LetRec) error {
	for _, bind := range letrec.Bindings {
		if lam, ok := bind.Value.(*core.Lambda); ok {
			exported := g.isExported(bind.Name)
			if err := g.generateFuncFromLambda(bind.Name, lam, exported); err != nil {
				return err
			}
		}
	}
	return nil
}

// generateFuncFromLambda generates a Go function from a Lambda expression.
func (g *Generator) generateFuncFromLambda(name string, lam *core.Lambda, exported bool) error {
	funcName := ToGoFuncName(name, exported)

	// Build parameter list
	var params []string
	for _, p := range lam.Params {
		// Type information would come from TypeInfo - for now use interface{}
		params = append(params, fmt.Sprintf("%s interface{}", ToGoVarName(p)))
	}

	g.writef("func %s(%s) interface{} {\n", funcName, strings.Join(params, ", "))
	g.indent++
	g.writef("return ")
	if err := g.generateExpr(lam.Body); err != nil {
		return err
	}
	g.writef("\n")
	g.indent--
	g.writef("}\n\n")

	return nil
}

// generateExpr generates Go code for a Core expression.
func (g *Generator) generateExpr(expr core.CoreExpr) error {
	switch e := expr.(type) {
	case *core.Lit:
		return g.generateLit(e)

	case *core.Var:
		g.write(ToGoVarName(e.Name))
		return nil

	case *core.VarGlobal:
		// Check if this is an ADT factory call (from elaboration)
		// Elaborator generates: $adt.make_TypeName_CtorName
		if e.Ref.Module == "$adt" && strings.HasPrefix(e.Ref.Name, "make_") {
			// Parse "make_TypeName_CtorName" to get the constructor info
			parts := strings.SplitN(e.Ref.Name[5:], "_", 2) // Skip "make_"
			if len(parts) == 2 {
				typeName := parts[0]
				ctorName := parts[1]
				// Generate Go constructor name: New + TypeName + CtorName
				goFuncName := "New" + ToPascalCase(typeName) + ToPascalCase(ctorName)

				// Check if this is a nullary constructor (needs to be called immediately)
				if ctorInfo, ok := g.adtConstructors[ctorName]; ok && ctorInfo.FieldCount == 0 {
					g.write(goFuncName + "()")
				} else {
					g.write(goFuncName)
				}
				return nil
			}
		}

		// Check if this is a registered ADT constructor by name
		if ctorInfo, ok := g.adtConstructors[e.Ref.Name]; ok {
			// Generate the proper constructor function call
			if ctorInfo.FieldCount == 0 {
				// Nullary constructor: call with no args
				g.write(ctorInfo.GoFuncName + "()")
			} else {
				// Constructor with fields - just reference the function
				// (it will be called with App)
				g.write(ctorInfo.GoFuncName)
			}
			return nil
		}
		// For other global references, use PascalCase
		g.write(ToPascalCase(e.Ref.Name))
		return nil

	case *core.Lambda:
		return g.generateLambda(e)

	case *core.App:
		return g.generateApp(e)

	case *core.Let:
		return g.generateLet(e)

	case *core.LetRec:
		return g.generateLetRec(e)

	case *core.If:
		return g.generateIf(e)

	case *core.Match:
		return g.generateMatch(e)

	case *core.BinOp:
		return g.generateBinOp(e)

	case *core.UnOp:
		return g.generateUnOp(e)

	case *core.Record:
		return g.generateRecord(e)

	case *core.RecordAccess:
		return g.generateRecordAccess(e)

	case *core.RecordUpdate:
		return g.generateRecordUpdate(e)

	case *core.List:
		return g.generateList(e)

	case *core.Tuple:
		return g.generateTuple(e)

	case *core.Intrinsic:
		return g.generateIntrinsic(e)

	case *core.DictRef:
		// Dictionary references are runtime-resolved
		g.writef("dict_%s_%s", e.ClassName, e.TypeName)
		return nil

	case *core.DictApp:
		return g.generateDictApp(e)

	default:
		return fmt.Errorf("unsupported expression type: %T", expr)
	}
}

// generateLit generates a Go literal.
func (g *Generator) generateLit(lit *core.Lit) error {
	switch lit.Kind {
	case core.IntLit:
		if v, ok := lit.Value.(int64); ok {
			g.writef("%d", v)
		} else if v, ok := lit.Value.(int); ok {
			g.writef("%d", v)
		} else {
			g.writef("%v", lit.Value)
		}
	case core.FloatLit:
		g.writef("%v", lit.Value)
	case core.BoolLit:
		g.writef("%v", lit.Value)
	case core.StringLit:
		g.writef("%q", lit.Value)
	case core.UnitLit:
		g.write("struct{}{}")
	default:
		return fmt.Errorf("unsupported literal kind: %v", lit.Kind)
	}
	return nil
}

// generateLambda generates a Go anonymous function.
func (g *Generator) generateLambda(lam *core.Lambda) error {
	var params []string
	for _, p := range lam.Params {
		params = append(params, fmt.Sprintf("%s interface{}", ToGoVarName(p)))
	}

	g.writef("func(%s) interface{} {\n", strings.Join(params, ", "))
	g.indent++
	g.writef("return ")
	if err := g.generateExpr(lam.Body); err != nil {
		return err
	}
	g.writef("\n")
	g.indent--
	g.write("}")

	return nil
}

// generateApp generates a Go function application.
func (g *Generator) generateApp(app *core.App) error {
	if err := g.generateExpr(app.Func); err != nil {
		return err
	}
	g.write("(")
	for i, arg := range app.Args {
		if i > 0 {
			g.write(", ")
		}
		if err := g.generateExpr(arg); err != nil {
			return err
		}
	}
	g.write(")")
	return nil
}

// generateLet generates a Go variable binding.
func (g *Generator) generateLet(let *core.Let) error {
	g.writef("func() interface{} {\n")
	g.indent++
	g.writef("%s := ", ToGoVarName(let.Name))
	if err := g.generateExpr(let.Value); err != nil {
		return err
	}
	g.writef("\n")
	g.writef("_ = %s // suppress unused\n", ToGoVarName(let.Name))
	g.writef("return ")
	if err := g.generateExpr(let.Body); err != nil {
		return err
	}
	g.writef("\n")
	g.indent--
	g.write("}()")
	return nil
}

// generateLetRec generates recursive function bindings.
func (g *Generator) generateLetRec(letrec *core.LetRec) error {
	g.writef("func() interface{} {\n")
	g.indent++

	// Declare all bindings first
	for _, bind := range letrec.Bindings {
		g.writef("var %s func(...interface{}) interface{}\n", ToGoVarName(bind.Name))
	}

	// Assign values
	for _, bind := range letrec.Bindings {
		g.writef("%s = func(args ...interface{}) interface{} {\n", ToGoVarName(bind.Name))
		g.indent++
		g.writef("return ")
		if err := g.generateExpr(bind.Value); err != nil {
			return err
		}
		g.writef("\n")
		g.indent--
		g.writef("}\n")
	}

	g.writef("return ")
	if err := g.generateExpr(letrec.Body); err != nil {
		return err
	}
	g.writef("\n")
	g.indent--
	g.write("}()")
	return nil
}

// generateIf generates a Go if expression.
func (g *Generator) generateIf(ifExpr *core.If) error {
	g.write("func() interface{} {\n")
	g.indent++
	g.writef("if ")
	if err := g.generateExpr(ifExpr.Cond); err != nil {
		return err
	}
	g.write(".(bool) {\n")
	g.indent++
	g.writef("return ")
	if err := g.generateExpr(ifExpr.Then); err != nil {
		return err
	}
	g.writef("\n")
	g.indent--
	g.writef("}\n")
	g.writef("return ")
	if err := g.generateExpr(ifExpr.Else); err != nil {
		return err
	}
	g.writef("\n")
	g.indent--
	g.write("}()")
	return nil
}

// generateMatch generates a Go switch statement for pattern matching.
func (g *Generator) generateMatch(match *core.Match) error {
	g.write("func() interface{} {\n")
	g.indent++

	// Evaluate scrutinee once
	g.writef("_scrutinee := ")
	if err := g.generateExpr(match.Scrutinee); err != nil {
		return err
	}
	g.writef("\n")
	g.writef("_ = _scrutinee // suppress unused\n")

	// Generate pattern matching - simplified for now
	g.writef("switch _s := _scrutinee.(type) {\n")
	for _, arm := range match.Arms {
		if err := g.generateMatchArm(&arm); err != nil {
			return err
		}
	}
	g.writef("default:\n")
	g.indent++
	g.writef("_ = _s\n")
	g.writef("panic(\"non-exhaustive match\")\n")
	g.indent--
	g.writef("}\n")

	g.indent--
	g.write("}()")
	return nil
}

// generateMatchArm generates a case clause for pattern matching.
func (g *Generator) generateMatchArm(arm *core.MatchArm) error {
	g.writef("case interface{}:\n")
	g.indent++
	g.writef("return ")
	if err := g.generateExpr(arm.Body); err != nil {
		return err
	}
	g.writef("\n")
	g.indent--
	return nil
}

// generateBinOp generates a Go binary operation.
func (g *Generator) generateBinOp(binop *core.BinOp) error {
	g.write("(")
	if err := g.generateExpr(binop.Left); err != nil {
		return err
	}
	g.writef(" %s ", g.mapOperator(binop.Op))
	if err := g.generateExpr(binop.Right); err != nil {
		return err
	}
	g.write(")")
	return nil
}

// generateUnOp generates a Go unary operation.
func (g *Generator) generateUnOp(unop *core.UnOp) error {
	g.writef("%s", g.mapUnaryOperator(unop.Op))
	return g.generateExpr(unop.Operand)
}

// generateRecord generates a Go struct literal.
func (g *Generator) generateRecord(rec *core.Record) error {
	g.write("map[string]interface{}{")
	first := true
	for name, value := range rec.Fields {
		if !first {
			g.write(", ")
		}
		first = false
		g.writef("%q: ", name)
		if err := g.generateExpr(value); err != nil {
			return err
		}
	}
	g.write("}")
	return nil
}

// generateRecordAccess generates field access.
func (g *Generator) generateRecordAccess(ra *core.RecordAccess) error {
	if err := g.generateExpr(ra.Record); err != nil {
		return err
	}
	g.writef(".(map[string]interface{})[%q]", ra.Field)
	return nil
}

// generateRecordUpdate generates Go code for a record update expression.
// AILANG: { base | field1: val1, field2: val2 }
// Go: RecordUpdate(base, map[string]interface{}{"field1": val1, ...})
func (g *Generator) generateRecordUpdate(ru *core.RecordUpdate) error {
	g.write("RecordUpdate(")
	if err := g.generateExpr(ru.Base); err != nil {
		return err
	}
	g.write(", map[string]interface{}{")

	first := true
	for field, val := range ru.Updates {
		if !first {
			g.write(", ")
		}
		first = false
		g.writef("%q: ", field)
		if err := g.generateExpr(val); err != nil {
			return err
		}
	}

	g.write("})")
	return nil
}

// generateList generates a Go slice literal.
func (g *Generator) generateList(list *core.List) error {
	g.write("[]interface{}{")
	for i, elem := range list.Elements {
		if i > 0 {
			g.write(", ")
		}
		if err := g.generateExpr(elem); err != nil {
			return err
		}
	}
	g.write("}")
	return nil
}

// generateTuple generates a Go struct for tuple.
func (g *Generator) generateTuple(tuple *core.Tuple) error {
	g.write("[]interface{}{")
	for i, elem := range tuple.Elements {
		if i > 0 {
			g.write(", ")
		}
		if err := g.generateExpr(elem); err != nil {
			return err
		}
	}
	g.write("}")
	return nil
}

// generateIntrinsic generates code for intrinsic operations.
func (g *Generator) generateIntrinsic(intr *core.Intrinsic) error {
	op := g.mapIntrinsicOp(intr.Op)
	if len(intr.Args) == 1 {
		// Unary
		g.writef("(%s", op)
		if err := g.generateExpr(intr.Args[0]); err != nil {
			return err
		}
		g.write(")")
	} else if len(intr.Args) == 2 {
		// Binary
		g.write("(")
		if err := g.generateExpr(intr.Args[0]); err != nil {
			return err
		}
		g.writef(" %s ", op)
		if err := g.generateExpr(intr.Args[1]); err != nil {
			return err
		}
		g.write(")")
	}
	return nil
}

// generateDictApp generates dictionary method application.
func (g *Generator) generateDictApp(da *core.DictApp) error {
	if err := g.generateExpr(da.Dict); err != nil {
		return err
	}
	g.writef(".%s(", ToPascalCase(da.Method))
	for i, arg := range da.Args {
		if i > 0 {
			g.write(", ")
		}
		if err := g.generateExpr(arg); err != nil {
			return err
		}
	}
	g.write(")")
	return nil
}

// mapOperator maps AILANG binary operators to Go operators.
func (g *Generator) mapOperator(op string) string {
	switch op {
	case "+", "-", "*", "/", "%":
		return op
	case "==", "!=", "<", ">", "<=", ">=":
		return op
	case "&&", "||":
		return op
	case "++":
		return "+" // Works for strings
	default:
		return op
	}
}

// mapUnaryOperator maps AILANG unary operators to Go operators.
func (g *Generator) mapUnaryOperator(op string) string {
	switch op {
	case "-":
		return "-"
	case "!":
		return "!"
	default:
		return op
	}
}

// mapIntrinsicOp maps intrinsic operations to Go operators.
func (g *Generator) mapIntrinsicOp(op core.IntrinsicOp) string {
	switch op {
	case core.OpAdd:
		return "+"
	case core.OpSub:
		return "-"
	case core.OpMul:
		return "*"
	case core.OpDiv:
		return "/"
	case core.OpMod:
		return "%"
	case core.OpEq:
		return "=="
	case core.OpNe:
		return "!="
	case core.OpLt:
		return "<"
	case core.OpLe:
		return "<="
	case core.OpGt:
		return ">"
	case core.OpGe:
		return ">="
	case core.OpConcat:
		return "+"
	case core.OpAnd:
		return "&&"
	case core.OpOr:
		return "||"
	case core.OpNot:
		return "!"
	case core.OpNeg:
		return "-"
	default:
		return "?"
	}
}

// Helper methods for output

func (g *Generator) write(s string) {
	g.buf.WriteString(strings.Repeat("\t", g.indent))
	g.buf.WriteString(s)
}

func (g *Generator) writef(format string, args ...interface{}) {
	g.buf.WriteString(strings.Repeat("\t", g.indent))
	fmt.Fprintf(&g.buf, format, args...)
}

func (g *Generator) formatOutput() ([]byte, error) {
	formatted, err := format.Source(g.buf.Bytes())
	if err != nil {
		// Return unformatted code with error for debugging
		return g.buf.Bytes(), fmt.Errorf("format error (raw code attached): %w", err)
	}
	return formatted, nil
}
