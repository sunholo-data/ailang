// generateDecl generates Go code for a Core declaration.
func (g *Generator) generateDecl(decl core.CoreExpr) error {
	switch d := decl.(type) {
	case *core.Let:
		return g.generateTopLevelLet(d)
	case *core.LetRec:
		return g.generateTopLevelLetRec(d)
	default:
		// Skip other declaration types for now
		return nil
	}
}

// isExported checks if a declaration name is marked for export.
func (g *Generator) isExported(name string) bool {
	if g.prog == nil || g.prog.Meta == nil {
		return false
	}
	if meta, ok := g.prog.Meta[name]; ok {
		return meta.IsExport
	}
	return false
}

// generateTopLevelLet generates a top-level let binding as a Go var or func.
func (g *Generator) generateTopLevelLet(let *core.Let) error {
	exported := g.isExported(let.Name)

	// Check if it's a function (Lambda body)
	if lam, ok := let.Value.(*core.Lambda); ok {
		return g.generateFuncFromLambda(let.Name, lam, exported)
	}

	// Otherwise generate as a variable
	varName := ToGoFuncName(let.Name, exported) // Use same naming for consistency
	g.writef("var %s = ", varName)
	if err := g.generateExpr(let.Value); err != nil {
		return err
	}
	g.writef("\n\n")
	return nil
}

// generateTopLevelLetRec generates recursive function bindings.
func (g *Generator) generateTopLevelLetRec(letrec *core.LetRec) error {
	for _, bind := range letrec.Bindings {
		if lam, ok := bind.Value.(*core.Lambda); ok {
			exported := g.isExported(bind.Name)
			if err := g.generateFuncFromLambda(bind.Name, lam, exported); err != nil {
				return err
			}
		}
	}
	return nil
}

// generateFuncFromLambda generates a Go function from a Lambda expression.
func (g *Generator) generateFuncFromLambda(name string, lam *core.Lambda, exported bool) error {
	funcName := ToGoFuncName(name, exported)

	// Register this function name mapping for recursive references
	g.topLevelFuncs[name] = funcName

	// Build parameter list
	var params []string
	for _, p := range lam.Params {
		// Type information would come from TypeInfo - for now use interface{}
		params = append(params, fmt.Sprintf("%s interface{}", ToGoVarName(p)))
	}

	g.writef("func %s(%s) interface{} {\n", funcName, strings.Join(params, ", "))
	g.indent++
	g.writef("return ")
	if err := g.generateExpr(lam.Body); err != nil {
		return err
	}
	g.writef("\n")
	g.indent--
	g.writef("}\n\n")

	return nil
}

// generateExpr generates Go code for a Core expression.
func (g *Generator) generateExpr(expr core.CoreExpr) error {
	switch e := expr.(type) {
	case *core.Lit:
		return g.generateLit(e)

	case *core.Var:
		// Check if this is a reference to a top-level function
		if goName, ok := g.topLevelFuncs[e.Name]; ok {
			g.write(goName)
		} else {
			g.write(ToGoVarName(e.Name))
		}
		return nil

	case *core.VarGlobal:
		// Check if this is an ADT factory call (from elaboration)
		// Elaborator generates: $adt.make_TypeName_CtorName
		if e.Ref.Module == "$adt" && strings.HasPrefix(e.Ref.Name, "make_") {
			// Parse "make_TypeName_CtorName" to get the constructor info
			parts := strings.SplitN(e.Ref.Name[5:], "_", 2) // Skip "make_"
			if len(parts) == 2 {
				typeName := parts[0]
				ctorName := parts[1]
				// Generate Go constructor name using proper naming to avoid double-prefix
				goFuncName := "New" + ToVariantStructName(typeName, ctorName)

				// Check if this is a nullary constructor (needs to be called immediately)
				if ctorInfo, ok := g.adtConstructors[ctorName]; ok && ctorInfo.FieldCount == 0 {
					g.write(goFuncName + "()")
				} else {
					g.write(goFuncName)
				}
				return nil
			}
		}

		// Check if this is a registered ADT constructor by name
		if ctorInfo, ok := g.adtConstructors[e.Ref.Name]; ok {
			// Generate the proper constructor function call
			if ctorInfo.FieldCount == 0 {
				// Nullary constructor: call with no args
				g.write(ctorInfo.GoFuncName + "()")
			} else {
				// Constructor with fields - just reference the function
				// (it will be called with App)
				g.write(ctorInfo.GoFuncName)
			}
			return nil
		}
		// For other global references, use PascalCase
		g.write(ToPascalCase(e.Ref.Name))
		return nil

	case *core.Lambda:
		return g.generateLambda(e)

	case *core.App:
		return g.generateApp(e)

	case *core.Let:
		return g.generateLet(e)

	case *core.LetRec:
		return g.generateLetRec(e)

	case *core.If:
		return g.generateIf(e)

	case *core.Match:
		return g.generateMatch(e)

	case *core.BinOp:
		return g.generateBinOp(e)

	case *core.UnOp:
		return g.generateUnOp(e)

	case *core.Record:
		return g.generateRecord(e)

	case *core.RecordAccess:
		return g.generateRecordAccess(e)

	case *core.RecordUpdate:
		return g.generateRecordUpdate(e)

	case *core.List:
		return g.generateList(e)

	case *core.Tuple:
		return g.generateTuple(e)

	case *core.Intrinsic:
		return g.generateIntrinsic(e)

	case *core.DictRef:
		// Dictionary references are runtime-resolved
		g.writef("dict_%s_%s", e.ClassName, e.TypeName)
		return nil

	case *core.DictApp:
		return g.generateDictApp(e)

	default:
		return fmt.Errorf("unsupported expression type: %T", expr)
	}
}

// generateLit generates a Go literal.
func (g *Generator) generateLit(lit *core.Lit) error {
	switch lit.Kind {
	case core.IntLit:
		if v, ok := lit.Value.(int64); ok {
			g.writef("%d", v)
		} else if v, ok := lit.Value.(int); ok {
			g.writef("%d", v)
		} else {
			g.writef("%v", lit.Value)
		}
	case core.FloatLit:
		g.writef("%v", lit.Value)
	case core.BoolLit:
		g.writef("%v", lit.Value)
	case core.StringLit:
		g.writef("%q", lit.Value)
	case core.UnitLit:
		g.write("struct{}{}")
	default:
		return fmt.Errorf("unsupported literal kind: %v", lit.Kind)
	}
	return nil
}

// generateLambda generates a Go anonymous function.
func (g *Generator) generateLambda(lam *core.Lambda) error {
	var params []string
	for _, p := range lam.Params {
		params = append(params, fmt.Sprintf("%s interface{}", ToGoVarName(p)))
	}

	g.writef("func(%s) interface{} {\n", strings.Join(params, ", "))
	g.indent++
	g.writef("return ")
	if err := g.generateExpr(lam.Body); err != nil {
		return err
	}
	g.writef("\n")
	g.indent--
	g.write("}")

	return nil
}

// generateApp generates a Go function application.
func (g *Generator) generateApp(app *core.App) error {
	// Special handling for cons operator (::)
	if v, ok := app.Func.(*core.Var); ok && v.Name == "::" {
		g.write("Cons(")
		for i, arg := range app.Args {
			if i > 0 {
				g.write(", ")
			}
			if err := g.generateExpr(arg); err != nil {
				return err
			}
		}
		g.write(")")
		return nil
	}
	// Also check for VarGlobal with :: name
	if v, ok := app.Func.(*core.VarGlobal); ok && v.Ref.Name == "::" {
		g.write("Cons(")
		for i, arg := range app.Args {
			if i > 0 {
				g.write(", ")
			}
			if err := g.generateExpr(arg); err != nil {
				return err
			}
		}
		g.write(")")
		return nil
	}

	// Check if function is a variable that needs type assertion
	needsAssertion := false
	if v, ok := app.Func.(*core.Var); ok {
		// Check if it's NOT a known top-level function
		if _, isTopLevel := g.topLevelFuncs[v.Name]; !isTopLevel {
			needsAssertion = true
		}
	}

	if needsAssertion {
		// Lambda stored in variable - needs type assertion
		g.write("CallFunc(")
		if err := g.generateExpr(app.Func); err != nil {
			return err
		}
		for _, arg := range app.Args {
			g.write(", ")
			if err := g.generateExpr(arg); err != nil {
				return err
			}
		}
		g.write(")")
	} else {
		if err := g.generateExpr(app.Func); err != nil {
			return err
		}
		g.write("(")
		for i, arg := range app.Args {
			if i > 0 {
				g.write(", ")
			}
			if err := g.generateExpr(arg); err != nil {
				return err
			}
		}
		g.write(")")
	}
	return nil
}

// generateLet generates a Go variable binding.
func (g *Generator) generateLet(let *core.Let) error {
	g.writef("func() interface{} {\n")
	g.indent++
	g.writef("%s := ", ToGoVarName(let.Name))
	if err := g.generateExpr(let.Value); err != nil {
		return err
	}
	g.writef("\n")
	g.writef("_ = %s // suppress unused\n", ToGoVarName(let.Name))
	g.writef("return ")
	if err := g.generateExpr(let.Body); err != nil {
		return err
	}
	g.writef("\n")
	g.indent--
	g.write("}()")
	return nil
}

// generateLetRec generates recursive function bindings.
func (g *Generator) generateLetRec(letrec *core.LetRec) error {
	g.writef("func() interface{} {\n")
	g.indent++

	// Declare all bindings first
	for _, bind := range letrec.Bindings {
		g.writef("var %s func(...interface{}) interface{}\n", ToGoVarName(bind.Name))
	}

	// Assign values
	for _, bind := range letrec.Bindings {
		g.writef("%s = func(args ...interface{}) interface{} {\n", ToGoVarName(bind.Name))
		g.indent++
		g.writef("return ")
		if err := g.generateExpr(bind.Value); err != nil {
			return err
		}
		g.writef("\n")
		g.indent--
		g.writef("}\n")
	}

	g.writef("return ")
	if err := g.generateExpr(letrec.Body); err != nil {
		return err
	}
	g.writef("\n")
	g.indent--
	g.write("}()")
	return nil
}

// generateIf generates a Go if expression.
func (g *Generator) generateIf(ifExpr *core.If) error {
	g.write("func() interface{} {\n")
	g.indent++
	g.writef("if ")
	if err := g.generateExpr(ifExpr.Cond); err != nil {
		return err
	}
	g.write(".(bool) {\n")
	g.indent++
	g.writef("return ")
	if err := g.generateExpr(ifExpr.Then); err != nil {
		return err
	}
	g.writef("\n")
	g.indent--
	g.writef("}\n")
	g.writef("return ")
	if err := g.generateExpr(ifExpr.Else); err != nil {
		return err
	}
	g.writef("\n")
	g.indent--
	g.write("}()")
	return nil
}

// generateMatch generates a Go switch statement for pattern matching.
func (g *Generator) generateMatch(match *core.Match) error {
	g.write("func() interface{} {\n")
	g.indent++

	// Evaluate scrutinee once
	g.writef("_scrutinee := ")
	if err := g.generateExpr(match.Scrutinee); err != nil {
		return err
	}
	g.writef("\n")
	g.writef("_ = _scrutinee // suppress unused\n")

	// Check if any patterns need if-else (list patterns can't use switch)
	needsIfElse := g.patternsNeedIfElse(match.Arms)

	if needsIfElse {
		// Use if-else chain for complex patterns (lists, etc.)
		return g.generateMatchIfElse(match)
	}

	// Determine if we need a type switch or value switch
	needsTypeSwitch := g.patternsNeedTypeSwitch(match.Arms)

	if needsTypeSwitch {
		// ADT constructor matching - use Kind-based switch
		// First, find the ADT type from constructor patterns
		var adtTypeName string
		for _, arm := range match.Arms {
			if cp, ok := arm.Pattern.(*core.ConstructorPattern); ok {
				if info, exists := g.adtConstructors[cp.Name]; exists {
					adtTypeName = info.TypeName
					break
				}
			}
		}
		if adtTypeName == "" {
			return fmt.Errorf("cannot determine ADT type for match expression")
		}

		// Assert scrutinee to ADT pointer type and switch on Kind
		goADTName := ToGoTypeName(adtTypeName)
		g.writef("_adt := _scrutinee.(*%s)\n", goADTName)
		g.writef("switch _adt.Kind {\n")
		hasDefault := false
		for _, arm := range match.Arms {
			if isWildcardOrVarPattern(arm.Pattern) {
				hasDefault = true
			}
			if err := g.generateMatchArmADT(&arm, adtTypeName); err != nil {
				return err
			}
		}
		if !hasDefault {
			g.writef("default:\n")
			g.indent++
			g.writef("panic(\"non-exhaustive match\")\n")
			g.indent--
		}
	} else {
		// Value switch for literals and wildcards
		g.writef("switch _scrutinee {\n")
		hasDefault := false
		for _, arm := range match.Arms {
			if isWildcardOrVarPattern(arm.Pattern) {
				if hasDefault {
					continue // Skip duplicate default
				}
				hasDefault = true
				g.writef("default:\n")
				g.indent++
				g.writef("return ")
				if err := g.generateExpr(arm.Body); err != nil {
					return err
				}
				g.writef("\n")
				g.indent--
			} else {
				if err := g.generateMatchArmValueSwitch(&arm); err != nil {
					return err
				}
			}
		}
		if !hasDefault {
			g.writef("default:\n")
			g.indent++
			g.writef("panic(\"non-exhaustive match\")\n")
			g.indent--
		}
	}
	g.writef("}\n")

	g.indent--
	g.write("}()")
	return nil
}

// generateMatchIfElse generates if-else chains for complex pattern matching.
func (g *Generator) generateMatchIfElse(match *core.Match) error {
	first := true
	for _, arm := range match.Arms {
		if isWildcardOrVarPattern(arm.Pattern) {
			// Wildcard/var is the else case
			if first {
				g.writef("// default case\n")
			} else {
				g.writef("} else {\n")
			}
			g.indent++

			// If it's a VarPattern, bind the variable
			if vp, ok := arm.Pattern.(*core.VarPattern); ok {
				g.writef("%s := _scrutinee\n", ToGoVarName(vp.Name))
				g.writef("_ = %s // suppress unused\n", ToGoVarName(vp.Name))
			}

			g.writef("return ")
			if err := g.generateExpr(arm.Body); err != nil {
				return err
			}
			g.writef("\n")
			g.indent--
			if !first {
				g.writef("}\n")
			}
			g.indent--
			g.write("}()")
			return nil
		}

		cond, bindings, err := g.generatePatternCondition(arm.Pattern, "_scrutinee")
		if err != nil {
			return err
		}

		if first {
			g.writef("if %s {\n", cond)
			first = false
		} else {
			g.writef("} else if %s {\n", cond)
		}
		g.indent++

		// Generate bindings
		for _, binding := range bindings {
			g.writef("%s\n", binding)
		}

		g.writef("return ")
		if err := g.generateExpr(arm.Body); err != nil {
			return err
		}
		g.writef("\n")
		g.indent--
	}

	// No wildcard - add panic
	if first {
		g.writef("panic(\"non-exhaustive match\")\n")
	} else {
		g.writef("} else {\n")
		g.indent++
		g.writef("panic(\"non-exhaustive match\")\n")
		g.indent--
		g.writef("}\n")
	}

	g.indent--
	g.write("}()")
	return nil
}

// generatePatternCondition generates the condition for a pattern and variable bindings.
func (g *Generator) generatePatternCondition(p core.CorePattern, scrutinee string) (string, []string, error) {
	var bindings []string

	switch pat := p.(type) {
	case *core.LitPattern:
		switch v := pat.Value.(type) {
		case int64:
			return fmt.Sprintf("%s == int64(%d)", scrutinee, v), nil, nil
		case int:
			return fmt.Sprintf("%s == int64(%d)", scrutinee, v), nil, nil
		case float64:
			return fmt.Sprintf("%s == float64(%v)", scrutinee, v), nil, nil
		case bool:
			return fmt.Sprintf("%s == %v", scrutinee, v), nil, nil
		case string:
			return fmt.Sprintf("%s == %q", scrutinee, v), nil, nil
		default:
			return fmt.Sprintf("%s == %v", scrutinee, v), nil, nil
		}

	case *core.ListPattern:
		if len(pat.Elements) == 0 && pat.Tail == nil {
			// Empty list: []
			return fmt.Sprintf("ListLen(%s) == 0", scrutinee), nil, nil
		}
		// List with elements or cons pattern
		if pat.Tail != nil {
			// Cons pattern: head :: tail or [a, b, ...rest]
			minLen := len(pat.Elements)
			cond := fmt.Sprintf("ListLen(%s) >= %d", scrutinee, minLen)

			// Bind head elements
			for i, elem := range pat.Elements {
				if vp, ok := elem.(*core.VarPattern); ok {
					binding := fmt.Sprintf("%s := ListHead(%s)", ToGoVarName(vp.Name), scrutinee)
					bindings = append(bindings, binding)
					bindings = append(bindings, fmt.Sprintf("_ = %s // suppress unused", ToGoVarName(vp.Name)))
					// For next element, need to get from tail
					if i < len(pat.Elements)-1 {
						scrutinee = fmt.Sprintf("ListTail(%s)", scrutinee)
					}
				}
			}

			// Bind tail
			if tailPat, ok := (*pat.Tail).(*core.VarPattern); ok {
				// Calculate tail start position
				if len(pat.Elements) > 0 {
					tailExpr := scrutinee
					for range pat.Elements {
						tailExpr = fmt.Sprintf("ListTail(%s)", tailExpr)
					}
					binding := fmt.Sprintf("%s := %s", ToGoVarName(tailPat.Name), tailExpr)
					bindings = append(bindings, binding)
					bindings = append(bindings, fmt.Sprintf("_ = %s // suppress unused", ToGoVarName(tailPat.Name)))
				} else {
					binding := fmt.Sprintf("%s := ListTail(%s)", ToGoVarName(tailPat.Name), scrutinee)
					bindings = append(bindings, binding)
					bindings = append(bindings, fmt.Sprintf("_ = %s // suppress unused", ToGoVarName(tailPat.Name)))
				}
			}

			return cond, bindings, nil
		}
		// Fixed-length list pattern
		cond := fmt.Sprintf("ListLen(%s) == %d", scrutinee, len(pat.Elements))
		return cond, bindings, nil

	case *core.VarPattern:
		// Var pattern always matches, binding is generated separately
		binding := fmt.Sprintf("%s := %s", ToGoVarName(pat.Name), scrutinee)
		bindings = append(bindings, binding)
		bindings = append(bindings, fmt.Sprintf("_ = %s // suppress unused", ToGoVarName(pat.Name)))
		return "true", bindings, nil

	case *core.WildcardPattern:
		return "true", nil, nil

	default:
		return "true", nil, nil
	}
}

// patternsNeedIfElse returns true if patterns need if-else (list patterns can't use switch).
func (g *Generator) patternsNeedIfElse(arms []core.MatchArm) bool {
	for _, arm := range arms {
		if _, ok := arm.Pattern.(*core.ListPattern); ok {
			return true
		}
	}
	return false
}

// patternsNeedTypeSwitch returns true if patterns include ADT constructors.
func (g *Generator) patternsNeedTypeSwitch(arms []core.MatchArm) bool {
	for _, arm := range arms {
		if _, ok := arm.Pattern.(*core.ConstructorPattern); ok {
			return true
		}
	}
	return false
}

// isWildcardOrVarPattern returns true if pattern is wildcard or variable binding.
func isWildcardOrVarPattern(p core.CorePattern) bool {
	switch p.(type) {
	case *core.WildcardPattern, *core.VarPattern:
		return true
	default:
		return false
	}
}

// generateMatchArmValueSwitch generates a case clause for value-based matching.
func (g *Generator) generateMatchArmValueSwitch(arm *core.MatchArm) error {
	switch p := arm.Pattern.(type) {
	case *core.LitPattern:
		switch v := p.Value.(type) {
		case int64:
			g.writef("case int64(%d):\n", v)
		case int:
			g.writef("case int64(%d):\n", v)
		case float64:
			g.writef("case float64(%v):\n", v)
		case bool:
			g.writef("case %v:\n", v)
		case string:
			g.writef("case %q:\n", v)
		default:
			g.writef("case %v:\n", v)
		}
	case *core.ListPattern:
		if len(p.Elements) == 0 {
			// Empty list pattern - check for empty slice
			g.writef("case []interface{}{}:\n")
		} else {
			// Non-empty list - needs more complex handling
			g.writef("default: // TODO: complex list pattern\n")
		}
	default:
		g.writef("default:\n")
	}
	g.indent++
	g.writef("return ")
	if err := g.generateExpr(arm.Body); err != nil {
		return err
	}
	g.writef("\n")
	g.indent--
	return nil
}

// generateMatchArmADT generates a case clause for ADT pattern matching.
// It uses Kind-based switching and binds constructor fields.
func (g *Generator) generateMatchArmADT(arm *core.MatchArm, adtTypeName string) error {
	switch p := arm.Pattern.(type) {
	case *core.ConstructorPattern:
		// Generate Kind case using proper naming convention
		kindConstName := ToKindConstName(adtTypeName, p.Name)
		g.writef("case %s:\n", kindConstName)
		g.indent++

		// Bind fields from the variant struct using proper naming convention
		if len(p.Args) > 0 {
			variantFieldName := ToVariantStructName(adtTypeName, p.Name)
			for i, arg := range p.Args {
				if vp, ok := arg.(*core.VarPattern); ok {
					goVarName := ToGoVarName(vp.Name)
					g.writef("%s := _adt.%s.Value%d\n", goVarName, variantFieldName, i)
					g.writef("_ = %s // suppress unused\n", goVarName)
				}
				// Wildcards don't need binding
			}
		}

		g.writef("return ")
		if err := g.generateExpr(arm.Body); err != nil {
			return err
		}
		g.writef("\n")
		g.indent--

	case *core.WildcardPattern:
		g.writef("default:\n")
		g.indent++
		g.writef("return ")
		if err := g.generateExpr(arm.Body); err != nil {
			return err
		}
		g.writef("\n")
		g.indent--

	case *core.VarPattern:
		g.writef("default:\n")
		g.indent++
		// Bind the variable to the entire ADT
		goVarName := ToGoVarName(p.Name)
		g.writef("%s := _adt\n", goVarName)
		g.writef("_ = %s // suppress unused\n", goVarName)
		g.writef("return ")
		if err := g.generateExpr(arm.Body); err != nil {
			return err
		}
		g.writef("\n")
		g.indent--

	default:
		return fmt.Errorf("unsupported pattern type in ADT match: %T", arm.Pattern)
	}
	return nil
}

// generateBinOp generates a Go binary operation.
func (g *Generator) generateBinOp(binop *core.BinOp) error {
	// Handle cons operator specially - it's not a simple binary op in Go
	if binop.Op == "::" {
		g.write("Cons(")
		if err := g.generateExpr(binop.Left); err != nil {
			return err
		}
		g.write(", ")
		if err := g.generateExpr(binop.Right); err != nil {
			return err
		}
		g.write(")")
		return nil
	}

	g.write("(")
	if err := g.generateExpr(binop.Left); err != nil {
		return err
	}
	g.writef(" %s ", g.mapOperator(binop.Op))
	if err := g.generateExpr(binop.Right); err != nil {
		return err
	}
	g.write(")")
	return nil
}

// generateUnOp generates a Go unary operation.
func (g *Generator) generateUnOp(unop *core.UnOp) error {
	g.writef("%s", g.mapUnaryOperator(unop.Op))
	return g.generateExpr(unop.Operand)
}

// generateRecord generates a Go struct literal.
func (g *Generator) generateRecord(rec *core.Record) error {
	g.write("map[string]interface{}{")
	first := true
	for name, value := range rec.Fields {
		if !first {
			g.write(", ")
		}
		first = false
		g.writef("%q: ", name)
		if err := g.generateExpr(value); err != nil {
			return err
		}
	}
	g.write("}")
	return nil
}

// generateRecordAccess generates field access.
