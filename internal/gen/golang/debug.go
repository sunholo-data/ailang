// Package golang provides Go code generation from AILANG Core AST.
//
// This file implements Debug effect codegen for M-GAME-E1.

package golang

import (
	"bytes"
	"fmt"
	"go/format"
)

// DebugGenerator generates Go code for Debug effect types and context.
type DebugGenerator struct {
	PackageName string
	buf         bytes.Buffer
	indent      int
}

// NewDebugGenerator creates a new Debug code generator.
func NewDebugGenerator(packageName string) *DebugGenerator {
	return &DebugGenerator{
		PackageName: packageName,
	}
}

// GenerateDebugTypes generates the debug_types.go file content.
// This includes DebugOutput, LogEntry, AssertionResult, and DebugContext.
// For release mode with build tags, use GenerateDebugTypesDebug and GenerateDebugTypesRelease.
func (g *DebugGenerator) GenerateDebugTypes() ([]byte, error) {
	g.buf.Reset()
	g.indent = 0

	// Write package header (no build tag - works in both modes)
	g.writeln("// Code generated by ailang. DO NOT EDIT.")
	g.writeln("// This file contains Debug effect types and context.")
	g.writeln("")
	g.writef("package %s\n\n", g.PackageName)

	// Generate DebugOutput type
	g.generateDebugOutput()

	// Generate LogEntry type
	g.generateLogEntry()

	// Generate AssertionResult type
	g.generateAssertionResult()

	// Generate DebugContext
	g.generateDebugContext()

	// Format the generated code
	formatted, err := format.Source(g.buf.Bytes())
	if err != nil {
		return g.buf.Bytes(), fmt.Errorf("format error: %w", err)
	}
	return formatted, nil
}

func (g *DebugGenerator) generateDebugOutput() {
	g.writeln("// DebugOutput contains collected debug data.")
	g.writeln("// Matches std/debug/types.ail schema.")
	g.writeln("type DebugOutput struct {")
	g.indent++
	g.writeln("Logs       []LogEntry")
	g.writeln("Assertions []AssertionResult")
	g.indent--
	g.writeln("}")
	g.writeln("")
}

func (g *DebugGenerator) generateLogEntry() {
	g.writeln("// LogEntry represents a single debug log entry.")
	g.writeln("type LogEntry struct {")
	g.indent++
	g.writeln("Message   string // Log message")
	g.writeln("Location  string // Source location (file:line)")
	g.writeln("Timestamp int64  // Logical time (host-defined)")
	g.indent--
	g.writeln("}")
	g.writeln("")
}

func (g *DebugGenerator) generateAssertionResult() {
	g.writeln("// AssertionResult represents a single assertion result.")
	g.writeln("type AssertionResult struct {")
	g.indent++
	g.writeln("Passed   bool   // Whether assertion passed")
	g.writeln("Message  string // Assertion message")
	g.writeln("Location string // Source location (file:line)")
	g.indent--
	g.writeln("}")
	g.writeln("")
}

func (g *DebugGenerator) generateDebugContext() {
	// Struct definition
	g.writeln("// DebugContext is the host-side Debug effect handler.")
	g.writeln("// Implements the Debug effect contract: write-only from AILANG,")
	g.writeln("// host-controlled collection and lifecycle.")
	g.writeln("type DebugContext struct {")
	g.indent++
	g.writeln("logs       []LogEntry")
	g.writeln("assertions []AssertionResult")
	g.writeln("timestamp  int64")
	g.indent--
	g.writeln("}")
	g.writeln("")

	// Constructor
	g.writeln("// NewDebugContext creates a new Debug context.")
	g.writeln("func NewDebugContext() *DebugContext {")
	g.indent++
	g.writeln("return &DebugContext{}")
	g.indent--
	g.writeln("}")
	g.writeln("")

	// SetTimestamp
	g.writeln("// SetTimestamp sets the logical timestamp for subsequent operations.")
	g.writeln("// The meaning of timestamp is host-defined (tick, test index, etc).")
	g.writeln("func (d *DebugContext) SetTimestamp(t int64) {")
	g.indent++
	g.writeln("d.timestamp = t")
	g.indent--
	g.writeln("}")
	g.writeln("")

	// Log
	g.writeln("// Log records a debug message.")
	g.writeln("// Location is auto-injected by the AILANG compiler.")
	g.writeln("func (d *DebugContext) Log(msg, location string) {")
	g.indent++
	g.writeln("d.logs = append(d.logs, LogEntry{")
	g.indent++
	g.writeln("Message:   msg,")
	g.writeln("Location:  location,")
	g.writeln("Timestamp: d.timestamp,")
	g.indent--
	g.writeln("})")
	g.indent--
	g.writeln("}")
	g.writeln("")

	// Assert
	g.writeln("// Assert records an assertion result.")
	g.writeln("// Location is auto-injected by the AILANG compiler.")
	g.writeln("func (d *DebugContext) Assert(cond bool, msg, location string) {")
	g.indent++
	g.writeln("d.assertions = append(d.assertions, AssertionResult{")
	g.indent++
	g.writeln("Passed:   cond,")
	g.writeln("Message:  msg,")
	g.writeln("Location: location,")
	g.indent--
	g.writeln("})")
	g.indent--
	g.writeln("}")
	g.writeln("")

	// Collect (HOST-ONLY)
	g.writeln("// Collect returns accumulated debug data.")
	g.writeln("// HOST-ONLY: Not callable from AILANG code.")
	g.writeln("func (d *DebugContext) Collect() DebugOutput {")
	g.indent++
	g.writeln("return DebugOutput{")
	g.indent++
	g.writeln("Logs:       d.logs,")
	g.writeln("Assertions: d.assertions,")
	g.indent--
	g.writeln("}")
	g.indent--
	g.writeln("}")
	g.writeln("")

	// Reset
	g.writeln("// Reset clears the debug buffer for the next step.")
	g.writeln("func (d *DebugContext) Reset() {")
	g.indent++
	g.writeln("d.logs = d.logs[:0]")
	g.writeln("d.assertions = d.assertions[:0]")
	g.indent--
	g.writeln("}")
	g.writeln("")

	// HasFailedAssertions
	g.writeln("// HasFailedAssertions returns true if any assertions failed.")
	g.writeln("func (d *DebugContext) HasFailedAssertions() bool {")
	g.indent++
	g.writeln("for _, a := range d.assertions {")
	g.indent++
	g.writeln("if !a.Passed {")
	g.indent++
	g.writeln("return true")
	g.indent--
	g.writeln("}")
	g.indent--
	g.writeln("}")
	g.writeln("return false")
	g.indent--
	g.writeln("}")
	g.writeln("")

	// FailedAssertions
	g.writeln("// FailedAssertions returns all failed assertions.")
	g.writeln("func (d *DebugContext) FailedAssertions() []AssertionResult {")
	g.indent++
	g.writeln("var failed []AssertionResult")
	g.writeln("for _, a := range d.assertions {")
	g.indent++
	g.writeln("if !a.Passed {")
	g.indent++
	g.writeln("failed = append(failed, a)")
	g.indent--
	g.writeln("}")
	g.indent--
	g.writeln("}")
	g.writeln("return failed")
	g.indent--
	g.writeln("}")
}

// Helper methods for output

func (g *DebugGenerator) writeln(s string) {
	for i := 0; i < g.indent; i++ {
		g.buf.WriteString("\t")
	}
	g.buf.WriteString(s)
	g.buf.WriteString("\n")
}

func (g *DebugGenerator) writef(format string, args ...interface{}) {
	for i := 0; i < g.indent; i++ {
		g.buf.WriteString("\t")
	}
	fmt.Fprintf(&g.buf, format, args...)
}

// GenerateDebugTypesRelease generates a no-op debug_types_release.go file.
// In release mode, Debug operations are zero-cost stubs.
func (g *DebugGenerator) GenerateDebugTypesRelease() ([]byte, error) {
	g.buf.Reset()
	g.indent = 0

	// Write package header with release build tag
	g.writeln("//go:build release")
	g.writeln("")
	g.writeln("// Code generated by ailang. DO NOT EDIT.")
	g.writeln("// Release mode: Debug effect operations are no-ops (zero cost).")
	g.writeln("")
	g.writef("package %s\n\n", g.PackageName)

	// Generate shared types (same as debug mode)
	g.generateDebugOutput()
	g.generateLogEntry()
	g.generateAssertionResult()

	// Generate no-op DebugContext
	g.generateDebugContextRelease()

	// Format the generated code
	formatted, err := format.Source(g.buf.Bytes())
	if err != nil {
		return g.buf.Bytes(), fmt.Errorf("format error: %w", err)
	}
	return formatted, nil
}

// GenerateDebugTypesDebug generates debug_types_debug.go file for debug builds.
// This is the full implementation with actual logging.
func (g *DebugGenerator) GenerateDebugTypesDebug() ([]byte, error) {
	g.buf.Reset()
	g.indent = 0

	// Write package header with debug build tag
	g.writeln("//go:build !release")
	g.writeln("")
	g.writeln("// Code generated by ailang. DO NOT EDIT.")
	g.writeln("// Debug mode: Debug effect operations collect trace data.")
	g.writeln("")
	g.writef("package %s\n\n", g.PackageName)

	// Generate shared types
	g.generateDebugOutput()
	g.generateLogEntry()
	g.generateAssertionResult()

	// Generate full DebugContext
	g.generateDebugContext()

	// Format the generated code
	formatted, err := format.Source(g.buf.Bytes())
	if err != nil {
		return g.buf.Bytes(), fmt.Errorf("format error: %w", err)
	}
	return formatted, nil
}

func (g *DebugGenerator) generateDebugContextRelease() {
	// Struct definition (minimal for release)
	g.writeln("// DebugContext is the host-side Debug effect handler.")
	g.writeln("// RELEASE MODE: All operations are no-ops (zero cost).")
	g.writeln("type DebugContext struct{}")
	g.writeln("")

	// Constructor
	g.writeln("// NewDebugContext creates a new Debug context (no-op in release).")
	g.writeln("func NewDebugContext() *DebugContext {")
	g.indent++
	g.writeln("return &DebugContext{}")
	g.indent--
	g.writeln("}")
	g.writeln("")

	// SetTimestamp (no-op)
	g.writeln("// SetTimestamp is a no-op in release mode.")
	g.writeln("func (d *DebugContext) SetTimestamp(t int64) {}")
	g.writeln("")

	// Log (no-op)
	g.writeln("// Log is a no-op in release mode.")
	g.writeln("func (d *DebugContext) Log(msg, location string) {}")
	g.writeln("")

	// Assert (no-op)
	g.writeln("// Assert is a no-op in release mode.")
	g.writeln("func (d *DebugContext) Assert(cond bool, msg, location string) {}")
	g.writeln("")

	// Collect (returns empty)
	g.writeln("// Collect returns empty output in release mode.")
	g.writeln("func (d *DebugContext) Collect() DebugOutput {")
	g.indent++
	g.writeln("return DebugOutput{}")
	g.indent--
	g.writeln("}")
	g.writeln("")

	// Reset (no-op)
	g.writeln("// Reset is a no-op in release mode.")
	g.writeln("func (d *DebugContext) Reset() {}")
	g.writeln("")

	// HasFailedAssertions (always false in release)
	g.writeln("// HasFailedAssertions always returns false in release mode.")
	g.writeln("func (d *DebugContext) HasFailedAssertions() bool {")
	g.indent++
	g.writeln("return false")
	g.indent--
	g.writeln("}")
	g.writeln("")

	// FailedAssertions (returns nil in release)
	g.writeln("// FailedAssertions returns nil in release mode.")
	g.writeln("func (d *DebugContext) FailedAssertions() []AssertionResult {")
	g.indent++
	g.writeln("return nil")
	g.indent--
	g.writeln("}")
}

