package strutil

import (
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"os"
	"sort"
	"testing"

	"golang.org/x/text/unicode/norm"
)

// nfc_tables.go is generated from golang.org/x/text/unicode/norm (the
// normaliser the loader uses, lexer.Normalize) so that the quoting rule can be
// decided with the standard library alone — strutil.QuoteTo and the Go
// emitter's copy of it (internal/gen/golang) share these tables.
//
//	go test ./internal/strutil -run TestNFCTablesUpToDate -update-nfc
var updateNFC = flag.Bool("update-nfc", false, "rewrite nfc_tables.go from golang.org/x/text")

const nfcTablesFile = "nfc_tables.go"

func generateNFCTables() []byte {
	type cccRange struct {
		lo, hi rune
		ccc    uint8
	}
	var cccs []cccRange
	var decompKeys []rune
	var decompData []rune
	var decompOff []uint16
	type pair struct{ a, b, c rune }
	var pairs []pair
	for r := rune(0); r <= 0x10FFFF; r++ {
		if r >= 0xD800 && r <= 0xDFFF {
			continue
		}
		s := string(r)
		ccc := norm.NFD.PropertiesString(s).CCC()
		if ccc != 0 {
			if n := len(cccs); n > 0 && cccs[n-1].hi == r-1 && cccs[n-1].ccc == ccc {
				cccs[n-1].hi = r
			} else {
				cccs = append(cccs, cccRange{r, r, ccc})
			}
		}
		if r >= hangulSBase && r < hangulSBase+hangulSCount {
			continue // algorithmic (nfc.go)
		}
		nfd := norm.NFD.String(s)
		if nfd == s {
			continue
		}
		d := []rune(nfd)
		decompKeys = append(decompKeys, r)
		decompOff = append(decompOff, uint16(len(decompData)))
		decompData = append(decompData, d...)
		// A primary composite: NFC keeps it, and it composes from (NFC of
		// its decomposition minus the last rune, that last rune).
		if norm.NFC.String(s) == s && len(d) >= 2 {
			head := []rune(norm.NFC.String(string(d[:len(d)-1])))
			if len(head) == 1 && norm.NFC.String(string(head[0])+string(d[len(d)-1])) == s {
				pairs = append(pairs, pair{head[0], d[len(d)-1], r})
			}
		}
	}
	decompOff = append(decompOff, uint16(len(decompData)))
	sort.Slice(pairs, func(i, j int) bool {
		if pairs[i].a != pairs[j].a {
			return pairs[i].a < pairs[j].a
		}
		return pairs[i].b < pairs[j].b
	})

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by nfc_gen_test.go (go test ./internal/strutil -run TestNFCTablesUpToDate -update-nfc). DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "package strutil\n\n")
	fmt.Fprintf(&b, "// nfcUnicodeVersion is the Unicode version of golang.org/x/text/unicode/norm\n// these tables were generated from.\nconst nfcUnicodeVersion = %q\n\n", norm.Version)
	fmt.Fprintf(&b, "// nfcCCCTable: [lo, hi, ccc] for every run of runes with a non-zero canonical combining class.\nvar nfcCCCTable = [...][3]int32{\n")
	for i, c := range cccs {
		fmt.Fprintf(&b, "{0x%X, 0x%X, %d}, ", c.lo, c.hi, c.ccc)
		if i%8 == 7 {
			b.WriteString("\n")
		}
	}
	fmt.Fprintf(&b, "}\n\n// nfcDecompKeys: runes with a canonical decomposition (Hangul syllables are algorithmic).\nvar nfcDecompKeys = [...]int32{")
	for i, k := range decompKeys {
		if i%20 == 0 {
			b.WriteString("\n")
		}
		fmt.Fprintf(&b, "0x%X, ", k)
	}
	fmt.Fprintf(&b, "\n}\n\n// nfcDecompOff[i]:nfcDecompOff[i+1] is the full canonical decomposition of nfcDecompKeys[i] in nfcDecompData.\nvar nfcDecompOff = [...]uint16{")
	for i, o := range decompOff {
		if i%32 == 0 {
			b.WriteString("\n")
		}
		fmt.Fprintf(&b, "%d, ", o)
	}
	fmt.Fprintf(&b, "\n}\n\nvar nfcDecompData = [...]int32{")
	for i, d := range decompData {
		if i%24 == 0 {
			b.WriteString("\n")
		}
		fmt.Fprintf(&b, "0x%X, ", d)
	}
	fmt.Fprintf(&b, "\n}\n\n// nfcCompTable: primary composites {first, second, composite}, sorted by (first, second).\nvar nfcCompTable = [...][3]int32{\n")
	for i, p := range pairs {
		fmt.Fprintf(&b, "{0x%X, 0x%X, 0x%X}, ", p.a, p.b, p.c)
		if i%6 == 5 {
			b.WriteString("\n")
		}
	}
	b.WriteString("\n}\n\n")
	fmt.Fprintf(&b, "// nfcNonStarterExtra: {rune, leading, trailing} stream-safe non-starter counts where x/text's\n"+
		"// differ from the canonical rule in nfcNonStarters (x/text counts over the COMPATIBILITY decomposition).\n"+
		"var nfcNonStarterExtra = [...][3]int32{\n")
	seconds := make([]rune, len(pairs))
	for i, p := range pairs {
		seconds[i] = p.b
	}
	for i, e := range nonStarterExtra(seconds) {
		fmt.Fprintf(&b, "{0x%X, %d, %d}, ", e[0], e[1], e[2])
		if i%8 == 7 {
			b.WriteString("\n")
		}
	}
	b.WriteString("\n}\n")
	out, err := format.Source(b.Bytes())
	if err != nil {
		panic(err)
	}
	return out
}

// nonStarterExtra applies x/text's rule (maketables.go: count the leading and
// trailing runes of the compatibility decomposition that have a non-zero class
// or combine backward; Hangul syllables trail 1 or 2) and keeps the runes
// where it differs from the same rule over the canonical decomposition, which
// nfcNonStarters computes from the other tables. TestNFCNonStartersMatchXText
// checks the result against x/text's behaviour, not against this rule.
func nonStarterExtra(seconds []rune) [][3]int32 {
	backward := map[rune]bool{}
	for _, r := range seconds {
		backward[r] = true
	}
	ns := func(x rune) bool {
		return norm.NFD.PropertiesString(string(x)).CCC() != 0 || backward[x] ||
			(x >= hangulVBase && x < hangulVBase+hangulVCount) || (x > hangulTBase && x < hangulTBase+hangulTCount)
	}
	count := func(d []rune) (lead, trail int) {
		for _, x := range d {
			if !ns(x) {
				break
			}
			lead++
		}
		for j := len(d) - 1; j >= 0 && ns(d[j]); j-- {
			trail++
		}
		return
	}
	var out [][3]int32
	for r := rune(0); r <= 0x10FFFF; r++ {
		if (r >= 0xD800 && r <= 0xDFFF) || (r >= hangulSBase && r < hangulSBase+hangulSCount) {
			continue
		}
		s := string(r)
		kl, kt := count([]rune(norm.NFKD.String(s)))
		cl, ct := count([]rune(norm.NFD.String(s)))
		if kl != cl || kt != ct {
			out = append(out, [3]int32{r, int32(kl), int32(kt)})
		}
	}
	return out
}

func TestNFCTablesUpToDate(t *testing.T) {
	want := generateNFCTables()
	if *updateNFC {
		if err := os.WriteFile(nfcTablesFile, want, 0o644); err != nil {
			t.Fatal(err)
		}
		return
	}
	got, err := os.ReadFile(nfcTablesFile)
	if err != nil {
		t.Fatal(err)
	}
	// A Windows checkout may give the file CRLF line endings.
	if !bytes.Equal(bytes.ReplaceAll(got, []byte("\r\n"), []byte("\n")), want) {
		t.Fatalf("%s is stale: the loader's normaliser (golang.org/x/text/unicode/norm) is Unicode %s with this x/text AND this Go toolchain "+
			"(x/text switches to newer Unicode tables under newer Go, e.g. 17.0.0 from go1.27). Regenerate: "+
			"go test ./internal/strutil -run TestNFCTablesUpToDate -update-nfc, then "+
			"go test ./internal/gen/golang -run TestEmittedQuoteRuntimeUpToDate -update-quote", nfcTablesFile, norm.Version)
	}
	if nfcUnicodeVersion != norm.Version {
		t.Fatalf("tables are Unicode %s but the loader normalises with Unicode %s (Go toolchain or x/text bump): regenerate with -update-nfc", nfcUnicodeVersion, norm.Version)
	}
}
