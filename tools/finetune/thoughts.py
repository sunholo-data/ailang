#!/usr/bin/env python3
"""Add a short thought (`reasoning`) to every assistant step of synthesized episodes (pilot-2).

Why: Ollama serves Gemma 4 with thinking ON, and after a tool result its parser expects
`<|channel>thought ... <channel|>` before the action. Pilot-1 was trained in thinking-OFF format,
and at eval its tool calls were intermittently filed as reasoning and lost (2026-11-06 trace).
Pilot-2 trains every step as thought -> action, rendered with enable_thinking=True.

The thoughts are BUILT FROM FACTS IN THE EPISODE, not generated by another model: the task,
the code's own imports and helpers, the real compiler error, the real diff, the real output.
They are short and correct by construction, and they state the habit being taught (read the
error, apply the fix it names, verify the output). Richer reasoning comes separately, from the
base model's own verified thinking (self-distillation).

  python3 tools/finetune/thoughts.py --episodes EP.jsonl --out EP_thought.jsonl
"""
import argparse
import difflib
import json
import os
import random
import re

READ = ["The task names the solution file; I'll read it first to see the template I must keep.",
        "Start by reading the solution file at the path the task gives.",
        "Read the template at the given path before writing anything."]
RUN = ["Run it and compare the output with the expected output exactly.",
       "Now run the program and check its output against the expected output.",
       "Verify: run it and compare line by line with the expected output."]
CHECK = ["Type-check it before running.", "Check that it compiles with the current toolchain.",
         "Run `ailang check` first; the compiler names what is wrong."]
DONE = ["The output matches exactly; the task is done.", "Output matches the expected output. Done."]

# Known error shapes -> the fix they name (each is what the compiler message itself says).
FIXES = [
    (r"`\+\+` is for lists only", "switch the string concatenation to `${{...}}` interpolation"),
    (r"undefined variable: print\b", "use `println`, since `print` is not in the prelude (or import `std/io (print)`)"),
    (r"undefined variable: (\w+).*add `import ([^`]+)`", "add the import the error names: `import {1}`"),
    (r"undefined variable: (\w+)", "import `{0}` from the module the error names (or use the right name)"),
    (r"MOD010.*module '([^']+)'.*(?:canonical|file) path '([^']+)'", "rename the module to match the file: `module {1}`"),
    (r"PAR015|bare assignment", "bind with `let`, since there is no assignment"),
    (r"PAR017|only valid inside", "use one style: `let x = e in ...` in an expression body, or a `{{ ...; ... }}` block body"),
    (r"PAR_MATCH_ARROW|next token to be =>", "write each match arm as `pattern => body`, with commas between arms"),
    (r"lambda parameter", "write the lambda as `\\x. body` (or `\\a b. body`)"),
    (r"INTERP_END", "keep only a plain expression inside `${{...}}`"),
    (r"in expression: as\b", "convert with `intToFloat`/`floatToInt` from `std/math`, since there is no `as` cast"),
    (r"Fractional\[int\]", "use integer division `/` on ints only, or convert with `intToFloat` first"),
    (r"PAR_UNEXPECTED_TOKEN at [^:]+:(\d+)", "fix the syntax at line {0}"),
    (r"PAR_NO_PREFIX_PARSE at [^:]+:(\d+)", "fix the expression at line {0}"),
    (r"type unification failed", "fix the type mismatch the checker reports"),
    (r"effect checking failed", "declare the effect the function performs"),
]


SPECIFIC = re.compile(r"\b(PAR[_A-Z0-9]*|TC_[A-Z0-9_]+|IMP\d+|MOD\d+)\b at |type error|undefined variable|effect checking failed|"
                      r"No instance|`\+\+`")


def first_error(text):
    # The specific line, not the "module loading error: failed to load ..." wrapper above it.
    for ln in text.splitlines():
        if SPECIFIC.search(ln) and "module loading error" not in ln:
            return re.sub(r"\s+", " ", ln.strip())[:200]
    for ln in text.splitlines():
        if "Error" in ln or "error" in ln or "PAR" in ln or "MOD0" in ln:
            return re.sub(r"\s+", " ", ln.strip())[:200]
    return re.sub(r"\s+", " ", text.strip().splitlines()[0])[:200] if text.strip() else ""


def fix_phrase(err):
    for pat, tmpl in FIXES:
        m = re.search(pat, err)
        if m:
            return tmpl.format(*m.groups())
    return "apply the fix the error describes"


def changed_lines(old, new):
    ops = difflib.SequenceMatcher(None, old.splitlines(), new.splitlines(), autojunk=False).get_opcodes()
    rows = [i1 + 1 for tag, i1, i2, j1, j2 in ops if tag != "equal"]
    if not rows:
        return ""
    lo = rows[0]
    hi = max(i2 for tag, i1, i2, j1, j2 in ops if tag != "equal")
    return f"line {lo}" if hi <= lo else f"lines {lo}-{hi}"


def plan_thought(code, task):
    imports = re.findall(r"^import\s+(std/[\w/]+)\s*\(([^)]*)\)", code, re.M)
    funcs = [f for f in re.findall(r"^(?:export\s+)?(?:pure\s+)?func\s+(\w+)", code, re.M) if f != "main"]
    exp = re.search(r"Expected output:\n(.*?)\n\n## ", task, re.S)
    n = len(exp.group(1).strip("\n").splitlines()) if exp else 0
    parts = []
    if imports:
        parts.append("use " + ", ".join(f"`{m} ({', '.join(x.strip() for x in fs.split(',')[:4])})`" for m, fs in imports[:3]))
    if funcs:
        parts.append("helpers " + ", ".join(f"`{f}`" for f in funcs[:4]))
    lead = "I'll write the full program at the given path, keeping `module benchmark/solution`"
    body = (": " + "; ".join(parts)) if parts else ""
    tail = f". It must print the {n} expected line{'s' if n != 1 else ''} exactly." if n else "."
    return lead + body + tail


def is_rewrite(steps, i):
    """A write that keeps under half of the previous file's lines: a rewrite, not a targeted fix."""
    c = steps[i]["call"]
    if c["name"] != "write":
        return False
    for s in reversed(steps[:i]):
        if s["call"]["name"] == "write":
            old, new = s["call"]["args"].get("content", ""), c["args"].get("content", "")
            return difflib.SequenceMatcher(None, old.splitlines(), new.splitlines(), autojunk=False).ratio() < 0.5
        if s["call"]["name"] == "edit":
            return False
    return False


BUILD = ["This program is long; write the helpers first with `main` as a stub, and check them before adding the rest.",
         "Build it in two steps: helpers and a stub `main` now, checked, then the rest. One huge write is easy to get wrong.",
         "Write the first part (helpers, `main` stubbed out) and type-check it before writing more."]
BUILD_REST = ["The helpers check cleanly. Now replace the stub `main` with the remaining helpers and the real `main`.",
              "That part compiles; add the rest of the program in place of the stub `main`."]
REWRITE = ["The attempt has too many errors to patch one by one; rewrite it cleanly, using only forms the reference shows.",
           "Too much of this is wrong to fix line by line; rewrite the program in plain, checked AILANG forms."]


def add_thoughts(ep, rnd):
    steps, out = ep["steps"], []
    for i, s in enumerate(steps):
        c, a = s["call"], s["call"]["args"]
        prev = steps[i - 1]["result"] if i else ""
        prev_call = steps[i - 1]["call"] if i else {}
        if s.get("habit") == "build":  # pilot-4: a long file is built in steps, never one huge write
            t = rnd.choice(BUILD)
        elif s.get("habit") == "build_rest":
            t = rnd.choice(BUILD_REST)
        elif i > 1 and not s.get("no_loss") and is_rewrite(steps, i):
            t = rnd.choice(REWRITE)
        elif c["name"] == "read":
            t = rnd.choice(READ)
        elif s.get("habit") == "reference":  # pilot-3, habit 5: look up instead of guessing again
            err = s.get("about") or first_error(prev)
            n_failed = s.get("after_failed", 0)
            where = (f"the exact signature of `{s['lookup']}`" if s.get("lookup_kind") == "signature"
                     else f"the \"{s['lookup']}\" section of the AILANG reference")
            if s.get("lookup_kind") == "signature" and n_failed >= 2:
                t = (f"That is {n_failed} fixes in a row for the same kind of error, and it still fails: {err} "
                     f"Patching again will not help. Check {where} and rewrite the call to match it.")
            elif s.get("lookup_kind") == "signature":
                t = f"The checker says: {err} Check {where} instead of guessing how to call it."
            elif n_failed >= 2:  # pilot-4: a loop. Stop patching; read, then rewrite the failing part
                t = (f"That is {n_failed} fixes in a row for the same kind of error, and it still fails: {err} "
                     f"Patching again will not help. Read the \"{s['lookup']}\" section of the AILANG reference "
                     f"and rewrite the failing part the way it shows.")
            elif any(x.get("failed_fix") for x in steps[:i]):
                t = (f"Still failing after my fix: {err} Guessing again will not help; read the "
                     f"\"{s['lookup']}\" section of the AILANG reference first.")
            else:
                t = f"The checker says: {err} Check the \"{s['lookup']}\" section of the AILANG reference before fixing it."
        elif c["name"] in ("write", "edit") and prev_call.get("name") == "bash" and \
                prev_call["args"].get("command", "").startswith(("ailang prompt", "ailang docs")) and \
                steps[i - 1].get("habit") == "reference":
            err = steps[i - 1].get("about") or ""
            t = f"The reference shows the correct form. So I'll {fix_phrase(err)}, following it exactly."
        elif c["name"] in ("write", "edit") and prev_call.get("name") == "bash" and \
                "ailang check" in prev_call["args"].get("command", "") and re.search(r"Error|PAR\w+|MOD0", prev):
            err = first_error(prev)
            where = changed_lines(a["edits"][0]["oldText"], a["edits"][0]["newText"]) if c["name"] == "edit" else ""
            t = f"The checker says: {err} So I'll {fix_phrase(err)}" + (f" ({where} of the edited block)." if where else ".")
        elif c["name"] in ("write", "edit") and prev_call.get("name") == "bash" and \
                "ailang run" in prev_call["args"].get("command", "") and i > 2:
            t = "The output differs from the expected output; fix the code that prints it, keeping the behaviour."
        elif c["name"] == "write":
            t = plan_thought(a.get("content", ""), ep["task_prompt"])
        elif s.get("habit") == "lookup":
            fn = s["lookup"].split(".")[-1]
            t = rnd.choice([f"Before writing, check the exact signature of `{fn}` instead of guessing it.",
                            f"Look up `{s['lookup']}` so I call it with the right arguments.",
                            f"Confirm how `{fn}` is declared in the current stdlib."])
        elif s.get("habit") == "examples":
            t = f"Find a working example that uses `{s['lookup']}` to follow its pattern."
        elif c["name"] == "bash" and "ailang check" in a.get("command", ""):
            t = rnd.choice(CHECK)
        else:
            t = rnd.choice(RUN)
        out.append(dict(s, thought=t))
    return dict(ep, steps=out, final_thought=rnd.choice(DONE))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--episodes", required=True)
    ap.add_argument("--out", required=True)
    ap.add_argument("--seed", type=int, default=5)
    a = ap.parse_args()
    rnd = random.Random(a.seed)
    n = 0
    with open(os.path.expanduser(a.out), "w") as f:
        for ln in open(os.path.expanduser(a.episodes)):
            f.write(json.dumps(add_thoughts(json.loads(ln), rnd)) + "\n")
            n += 1
    print(json.dumps({"episodes": n}))


if __name__ == "__main__":
    main()
